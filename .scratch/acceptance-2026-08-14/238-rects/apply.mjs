const raw = await readFile(FILE, "utf8");
const doc = JSON.parse(raw);
let touched = 0;
const report = [];

for (const room of doc.rooms) {
  for (const zone of room.zones) {
    const address = `${room.id}/${zone.key}`;
    const patch = PATCH[address];
    if (!patch) continue;
    const [x, y, w, h, remapNote] = patch;
    const was = { ...zone.rect };
    const wasBloom = zone.bloomAR;
    zone.rectOld = was;
    zone.rect = { x, y, w, h };
    zone.bloomAR = bloom(w, h);
    zone.remappedRound = 50;
    zone.remapNote = remapNote;
    zone.eyeChecked = true;
    zone.reshoot = true;
    zone.reshootReason =
      "Прямоугольник переразмечен тикетом 238 — прежний кадр проверялся против другого участка, порог надо прогнать заново";
    touched += 1;
    report.push(
      `${address.padEnd(16)} ${was.x},${was.y},${was.w},${was.h} → ${x},${y},${w},${h}   bloomAR ${wasBloom} → ${zone.bloomAR}`,
    );
  }
}

if (touched !== Object.keys(PATCH).length) {
  throw new Error(`ожидалось ${Object.keys(PATCH).length} зон, тронуто ${touched}`);
}

await writeFile(FILE, `${JSON.stringify(doc, null, 1)}\n`, "utf8");
console.log(report.join("\n"));
console.log(`\nтронуто зон: ${touched}`);
