// Точечная правка контракта — тикет 81, часть 2 (заход второй).
// Круг «разобрать → записать с отступом 2 + \n» воспроизводит файл байт-в-байт
// (проверено). Трогаем только свои поля.
import { readFile, writeFile } from "node:fs/promises";

const P = "design/package/handoff/rooms.json";
const raw = await readFile(P, "utf8");
const doc = JSON.parse(raw);
const zone = (roomId, key) => {
  const z = doc.rooms.find((r) => r.id === roomId)?.zones.find((x) => x.key === key);
  if (!z) throw new Error(`нет зоны ${roomId}/${key}`);
  return z;
};
const AR = (r) => Math.min(120, Math.max(30, Math.round((r.w / r.h) * 58)));
/** Переставить прямоугольник, сохранив прежний и пересчитав пятно. */
const remap = (z, rect, note, round = 15) => {
  z.rectOld = { ...z.rect };
  z.rect = rect;
  z.bloomAR = AR(rect);
  z.remappedRound = round;
  z.remapNote = note;
};

