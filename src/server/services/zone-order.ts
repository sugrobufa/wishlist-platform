// ПОРЯДОК ЗОН В ФОРМЕ ДОБАВЛЕНИЯ — ПО ДЕЛАМ, А НЕ ПО АНКЕТЕ (тикет 189).
//
// ЧТО БЫЛО. Порядок красил ответ на вопрос «Что чаще всего хочется?»: выбранные
// категории шли первыми. Владелец на приёмке 11.08.2026: «не ясно, зачем выбор,
// что хочется больше всего… ничего не происходит и непонятно, на что это
// влияет». Он описал механизм точно — ответ красил ровно две вещи, и обе
// невидимы в момент ответа: порядок наполнения стартовым набором (набор выпилен
// целиком, тикет 191) и вот этот порядок, увидеть который можно только уйдя на
// другой экран. Человек нажимал четыре раза и не получал ничего.
//
// ЧТО СТАЛО. Зоны, куда человек УЖЕ КЛАЛ ВЕЩИ, идут первыми; остальные —
// контрактным порядком пресета. Это точнее анкеты (дела честнее намерений) и не
// стоит человеку ни одного нажатия.
//
// ГРАНИЦА: ЭТО ТОЛЬКО СОРТИРОВКА. Ни одна зона не пропадает и не появляется,
// набор зон комнаты не трогается — что видно, решает `visibleZones` (инвариант
// №5), а здесь только очередь. Заготовки полок (`ZoneSet`) — не это: их выбирают
// в настройках, и они остаются.
//
// ПОЧЕМУ СЕРВИС, А НЕ ДВЕ СТРОКИ В СТРАНИЦЕ. Правило проверяется тестом на
// сервисе, а не на разметке (условие тикета): в разметке его видно только
// глазами, а сортировка — ровно тот код, который тихо разъезжается с
// требованием при следующей правке страницы.
import { countItemsByZone } from "@/server/services/items";

/**
 * Зоны, куда уже клали вещи, — первыми; порядок внутри каждой половины
 * сохраняется (контракт пресета).
 *
 * Функция чистая: две выборки вместо `sort`, потому что стабильность здесь не
 * деталь реализации, а само требование — «остальные контрактным порядком».
 */
export function orderZonesByDeeds<T extends { key: string }>(
  zones: readonly T[],
  counts: ReadonlyMap<string, number>,
): T[] {
  const used = (zone: T) => (counts.get(zone.key) ?? 0) > 0;
  return [...zones.filter(used), ...zones.filter((zone) => !used(zone))];
}

/**
 * То же для живой комнаты: счёт вещей по зонам берётся одним запросом.
 *
 * СЧИТАЮТСЯ ВСЕ ВЕЩИ ЗОНЫ, включая спрятанные и уехавшие в сокровищницу
 * (`countItemsByZone`). Это не небрежность: вопрос здесь — «клал ли человек
 * сюда хоть раз», а вещь, переехавшая в витрину, была положена именно в эту
 * зону и `zone` за собой сохранила (тикет 124). Пустая комната — счёт пуст, и
 * порядок выходит контрактным сам собой.
 */
export async function zonesByDeeds<T extends { key: string }>(
  roomId: string,
  zones: readonly T[],
): Promise<T[]> {
  return orderZonesByDeeds(zones, await countItemsByZone(roomId));
}
