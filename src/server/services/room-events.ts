// Лента «Что происходит» (тикет 114, доска 34c · турн 11e) — запись событий.
//
// ПРАВИЛО, КОТОРОЕ ВАЖНЕЕ ОСТАЛЬНЫХ. В ленту не попадает подарочный слой:
// ни брони, ни складчины, ни «что подарили» — ни в каком виде и ни для кого.
// Это правило доски (34c), и оно шире нашей осторожности: мы спрашивали
// только про хозяйку (инвариант №1), дизайн ответил «подарочный слой — не
// событие вообще». Поэтому здесь пять видов, и все про КОМНАТУ.
//
// ЗАПИСЬ ОТДЕЛЕНА ОТ ПОКАЗА СОЗНАТЕЛЬНО. Сам показ ленты ждёт трёх ответов
// дизайна (глубина памяти, склейка нескольких событий одного друга за день,
// показывать ли ленту новичку) — они заданы заданием 19. А записывать надо
// уже сейчас: событие — это факт «когда», и задним числом его не восстановить.
// Три вида из пяти не выводятся ни из чего: моментов смены интерьера,
// открытия сокровищницы и согласия не хранит никто.
import { Prisma } from "@prisma/client";
import { prisma } from "@/server/db";

/** Что кладём в payload — ровно то, что нужно СТРОКЕ ленты. */
export type RoomEventPayload =
  /** «У Милы появилась полка „Путешествия"» — ключ зоны, подпись возьмёт UI. */
  | { zone: string }
  /** «Комната Милы — теперь „Изумруд"» — id пресета, имя возьмёт UI. */
  | { preset: string }
  /** У остальных видов своих данных нет. */
  | Record<string, never>;

/**
 * Записать событие комнаты. Ошибку НЕ поднимает наверх: лента — украшение,
 * и падать из-за неё в середине «добавить вещь» или «сменить интерьер»
 * нельзя. Тот же приём, что у постановки писем в очередь.
 */
export async function recordRoomEvent(
  roomId: string,
  kind: "ITEMS_ADDED" | "SHELF_OPENED" | "TREASURY_OPENED" | "ROOM_CHANGED" | "BECAME_MUTUAL",
  payload: RoomEventPayload = {},
): Promise<void> {
  try {
    await prisma.roomEvent.create({
      data: { roomId, kind, payload: payload as Prisma.InputJsonObject },
    });
  } catch (error) {
    console.error(`[лента] событие ${kind} комнаты ${roomId} не записалось`, error);
  }
}

/**
 * События «вещь добавлена» и «появилась полка» — одним заходом из createItem.
 *
 * «Полка появилась» ставится, только когда вещь в зоне ПЕРВАЯ: считаем до
 * создания (`countBefore`), иначе первая же вещь второй зоны выглядела бы
 * как открытие первой.
 */
export async function recordItemAdded(
  roomId: string,
  zone: string,
  countBefore: number,
): Promise<void> {
  await recordRoomEvent(roomId, "ITEMS_ADDED", { zone });
  if (countBefore === 0) await recordRoomEvent(roomId, "SHELF_OPENED", { zone });
}
