// Словарь писем (тикет 32). Все слова, которые человек читает в письме,
// живут здесь — в mailer.ts остаются только сборка строк, ссылки и отправка.
//
// ПОЧЕМУ НЕ `messages/ru.json`. Продуктовый словарь отдаёт клиенту next-intl:
// он сериализуется в разметку КАЖДОЙ страницы (на этом уже обжигались в
// тикете 29, и тикет 25 отдельно записал правило «служебным строкам там не
// место»). Письма в браузере не рисуются ни разу — их текст уехал бы к
// каждому гостю мёртвым килобайтом. Поэтому словарь писем серверный, по
// образцу того, что было у `dev-login`: отдельный файл вне next-intl.
//
// ПОЧЕМУ .ts, А НЕ .json. Модуль в `src/server/` физически не может попасть в
// клиентский бандл: его импортирует только mailer, а тот тянет nodemailer.
// Плюс строки проверяются типами, а тест тона читает их обычным импортом,
// без чтения файла с диска.
//
// КОНТРАКТ ПИСЕМ — `design/package/handoff/round41/letters.json` (тикет 171):
// триггеры, темы, блоки, запреты и токены ТРЁХ писем (третье, хозяйке после
// праздника, приехало этим раундом). Сама вёрстка приехала готовой и лежит в
// `mail-templates.ts`; здесь — только слова, и каждое расхождение с контрактом
// объяснено на месте.
//
// РАСХОЖДЕНИЕ ПО ПРЕХЕДЕРАМ ЗАКРЫТО РАУНДОМ 42. Дизайн признал, что нарушил
// собственное правило рода в прехедерах обеих гостевых вёрсток, и прислал
// редакции — обе назывные, обе взяты сюда ДОСЛОВНО. Причина, которую он при
// этом записал, дороже самих строк: прехедер не считали текстом, потому что в
// вёрстке он спрятан в невидимом `<span>`, а в макете его нет вовсе. Человек
// читает его в списке входящих второй строкой после темы — и часто ВМЕСТО
// тела. Отсюда правило рода стало шире: оно проверяет ВСЕ поля письма — тему,
// прехедер, плашку, подвал, alt, — и это закреплено сторожем
// `tests/messages-tone.test.ts`, который читает не только словарь, но и
// контракт, и присланные вёрстки, и собранное письмо целиком.
//
// ОСТАЛОСЬ ОДНО РАСХОЖДЕНИЕ, И ОНО НАШЕ — прехедер письма хозяйке: контрактный
// дословно повторил бы нашу же ТЕМУ, и две самые заметные строки списка
// входящих сказали бы одно и то же. Записано поимённо
// (`tests/mail-round41.test.ts` → `PREHEADER_DRIFT`), чтобы следующий читатель
// не «синхронизировал» его обратно.
//
// ТОН — `design/package/handoff/tone.md`: везде «ты», ни одного
// восклицательного знака, ни одной родовой скобки, точка не ставится в конце
// короткой строки. СЛОВАРЬ — `messages/ru.json`: экраны и действия письмо
// зовёт ровно так же, как продукт («Мои подарки», «Освободить вещь», «Что
// подарили»), иначе человек получает письмо про одно, а приходит к другому.
// И то и другое закреплено тестом `tests/messages-tone.test.ts`.

