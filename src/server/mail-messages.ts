/**
 * Подстановка `{ключ}` в строку словаря. Неизвестное имя остаётся как есть —
 * «{owner}» в письме заметнее молчаливой пустоты.
 */
export function fillMail(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => values[key] ?? whole);
}
