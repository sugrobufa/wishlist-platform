// образцу того, что было у `dev-login`: отдельный файл вне next-intl.
//
// ПОЧЕМУ .ts, А НЕ .json. Модуль в `src/server/` физически не может попасть в
// клиентский бандл: его импортирует только mailer, а тот тянет nodemailer.
// Плюс строки проверяются типами, а тест тона читает их обычным импортом,
// без чтения файла с диска.
//
// КОНТРАКТ ПИСЕМ — `design/package/handoff/round41/letters.json` (тикет 171):
// триггеры, темы, блоки, запреты и токены ТРЁХ писем (третье, хозяйке после
// праздника, приехало этим раундом). Сама вёрстка приехала готовой и лежит в
// `mail-templates.ts`; здесь — только слова, и каждое расхождение с контрактом
// объяснено на месте.
//
// ГЛАВНОЕ РАСХОЖДЕНИЕ РАУНДА 41 — ПРЕХЕДЕРЫ ОБОИХ ГОСТЕВЫХ ПИСЕМ, и оно не
// наше. Дизайн написал новое правило рода («Ты обещал», «Мила убрала», «ты
// ничего не должен» запрещены — только назывные обороты), переписал по нему
// тела обеих вёрсток, а ПРЕХЕДЕРЫ НЕ ТРОНУЛ: в `letters.json` и в самих HTML
