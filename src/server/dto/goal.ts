// Копилка на мечту (ADR-0008, тикеты 44 и 54) — единственное место, где цель и
// участие превращаются в JSON. Форм ДВЕ, и это главное содержание файла.
//
// ПОЧЕМУ ДВЕ ФОРМЫ, А НЕ ОДНА С ФЛАГОМ. Копилка ведёт себя как складчина, и
// инвариант №1 (тихая бронь) распространяется на неё целиком:
//
//   хозяйке — цель и больше НИЧЕГО. Ни собранной суммы, ни числа участников,
//             ни имён, ни обещанных сумм. Прогресс своей копилки она не видит:
//             у себя в комнате она видит один общий счётчик «N вещей уже
//             забрали», где копилка считается ОДНОЙ вещью при любом числе
//             участников (services/goal.ownerTakenTotal);
//   гостю   — цель, прогресс сбора и «N человек уже скинулись»; имена
//             участников — ТОЛЬКО тому гостю, кто сам участвует (тикет 54).
//
// Форма хозяйки физически не содержит ключей прогресса: не «мы их не
// заполняем», а «их в типе нет». Так вопрос «а это поле хозяйке можно?» не
// приходится решать заново на каждом новом поле — ответ уже в форме. Имена
// пришли в гостевую форму и в форме хозяйки не появились — по той же причине.
//
// ИМЕНА МЕЖДУ УЧАСТНИКАМИ (тикет 54, ADR-0008, второе уточнение владельца от
// 06.08.2026, вопрос В4 реестра закрыт). Складчина — совместное действие:
// «имена перечисляем, а не считаем — „в складчине трое“ не даёт написать Ане,
// а ради этого имя и открыто» (доска, турн 25d). Открыты они РОВНО между
// участниками:
//
//   участник копилки          → видит имена остальных участников;
//   гость, который не скинулся → счётчик без имён, как было (ADR-0008:
//                                «нерешившимся гостям со стороны — по-прежнему
//                                счётчик без имён»);
//   хозяйка                    → ничего, до экрана «что подарили».
//
// Свой/чужой определяет сервер по cancelToken из HTTP-only cookie — тем же
// способом, что и флаг `mine`, а не по слову клиента.
//
// ИНВАРИАНТ №2 не смягчён: он про раскрытие имён ХОЗЯЙКЕ, и оно по-прежнему
// случается ровно один раз — на экране «что подарили», вместе с остальными
// дарителями (services/occasions.getOccasionView).
//
// ДЕНЬГИ. Суммы уезжают строками Decimal, валюта — отдельным полем ISO 4217
// (CLAUDE.md). Числом сумма не становится нигде: доля собранного считается
// на Decimal ниже, а Intl-форматирование живёт в компоненте.
import { Prisma, type GoalPledge, type RoomGoal } from "@prisma/client";

/** Цель глазами ХОЗЯЙКИ: на что копит, сколько, в какой валюте. И всё. */
export type OwnerGoalDto = {
  title: string;
  /** Decimal строкой — «45000.00». */
  amount: string;
  /** ISO 4217. */
  currency: string;
};

/** Цель глазами ГОСТЯ: то же плюс прогресс сбора и, участнику, имена соседей. */
export type GuestGoalDto = {
  title: string;
  amount: string;
  currency: string;
  /** Сумма НАЗВАННЫХ обещаний, строкой Decimal. */
  pledged: string;
  /** Сколько человек сказали «я участвую» — считаются все, и без суммы тоже. */
  participants: number;
  /** Доля собранного, 0…100, целыми процентами (полоса и «Собрано 36%»). */
  percent: number;
  /** Участвует ли ЭТОТ гость (по токену из его же cookie) — «ты участвуешь». */
  mine: boolean;
  /**
   * Кто ещё в складчине. `null` — гостю со стороны (он не участвует) и
   * участнику-одиночке: называть некого. Ни при каком раскладе здесь не
   * появляется имя самого зрителя — в строке он «ты».
   */
  who: GoalWhoDto | null;
};

/** Какая из четырёх строк 25d рисуется (`Booking.poolWho1/2/Many/You`). */
export type GoalWhoForm = "one" | "two" | "many" | "you";

/**
 * Значения для строки имён — ровно те, что подставятся в словарную строку, и
 * ни одним именем больше. Список участников целиком в JSON не уезжает: в
 * ответе столько имён, сколько видно на экране.
 */
export type GoalWhoDto = {
  form: GoalWhoForm;
  /** `{a}` — первое названное имя; есть во всех четырёх формах. */
  a: string;
  /** `{b}` — второе имя; только «двое» и «больше двух», иначе null. */
  b: string | null;
  /** `{rest}` — сколько участников не названы поимённо; в формах без «и ещё» 0. */
  rest: number;
};

/**
 * Длина имени в строке. Имя приходит из свободного поля (до 120 символов), а
 * строка живёт под полосой прогресса одним рядом — длинное имя не переносим,
 * а укорачиваем по границе слова. Падежей нет ни в одной из четырёх форм
 * (имя всюду стоит в именительном), поэтому склонять нечего.
 */
const MAX_NAME = 24;

function shortName(raw: string): string {
  const clean = raw.replace(/\s+/gu, " ").trim();
  if (clean.length <= MAX_NAME) return clean;
  const cut = clean.slice(0, MAX_NAME);
  // «Александра Константиновна Ш.» → «Александра…», а не «Александра Константи…»:
  // обрезок фамилии не сообщает ничего, а имени в строке хватает.
  const space = cut.lastIndexOf(" ");
  return `${space > 0 ? cut.slice(0, space) : cut.trimEnd()}…`;
}

/**
 * Четыре формы строки «кто в складчине» с доски (турн 25d):
 *
 *   один        → «в складчине {a}»                    `poolWho1`
 *   двое        → «в складчине {a} и {b}»              `poolWho2`
 *   больше двух → «в складчине {a}, {b} и ещё {rest}»  `poolWhoMany`
 *   ты внутри   → «ты, {a} и ещё {rest}»               `poolWhoYou`
 *
 * `names` — те, кого называем ПОИМЁННО (зрителя среди них нет: он «ты»).
 * `you` — зритель сам в складчине.
 *
 * Форма «ты внутри» называет одного соседа и считает остальных, поэтому она
 * включается с трёх соседей: на двоих «в складчине Аня и Катя» называет обоих,
 * а «ты, Аня и ещё 1» — одного, и доска просила именно перечислять. На одном
 * соседе «ты, Аня и ещё 0» было бы просто неправдой, и строки «ты и Аня» в
 * словаре нет — тогда работает «в складчине Аня»: что зритель участвует, ему
 * говорит соседняя строка «Ты участвуешь».
 *
 * Функция чистая и экспортируется ради теста на все четыре формы: форма
 * «больше двух» в продукте сейчас не рисуется — она для зрителя ВНЕ складчины,
 * а такому имён не показывают (см. шапку файла). Если владелец однажды откроет
 * имена и им, поменяется одно условие в `goalForGuest`, а не эта таблица.
 */
export function poolWho(
  names: readonly string[],
  options: { you?: boolean } = {},
): GoalWhoDto | null {
  const listed = names.map(shortName).filter((name) => name !== "");
  const [a, b] = listed;
  if (a === undefined) return null;
  if (options.you && listed.length >= 3) {
    return { form: "you", a, b: null, rest: listed.length - 1 };
  }
  if (b === undefined) return { form: "one", a, b: null, rest: 0 };
  if (listed.length === 2) return { form: "two", a, b, rest: 0 };
  return { form: "many", a, b, rest: listed.length - 2 };
}

/**
 * Цель хозяйке. Аргумент — строка БД целиком (со всеми участиями, если их
 * загрузили): allowlist из трёх полей отсекает остальное, даже когда relation
 * случайно оказался в объекте. Ровно тот же приём, что у `itemForOwner`,
 * и проверяется он так же — сериализацией целого объекта в тесте.
 */
export function goalForOwner(goal: RoomGoal | null | undefined): OwnerGoalDto | null {
  if (!goal) return null;
  return {
    title: goal.title,
    amount: goal.amount.toString(),
    currency: goal.currency,
  };
}

/**
 * Цель гостю: та же цель плюс прогресс. Отдельных сумм здесь нет ни своих, ни
 * чужих: гость видит ОБЩУЮ сумму и ОБЩЕЕ число, а «я участвую» ему
 * подтверждает флаг `mine`, а не строка с его именем.
 *
 * Имена появляются только у того, кто участвует сам (тикет 54): `myTokens` —
 * токены из HTTP-only cookie этого же гостя, и другого способа назваться
 * участником у клиента нет. Не участвует — `who: null`, ответ ровно тот же,
 * что был до тикета 54.
 *
 * Обещание без суммы («просто участвую») в сумму не входит, но участником
 * считается: иначе «трое скинулись» при пустой полосе выглядело бы ошибкой,
 * а не честной картиной.
 *
 * Порядок имён — порядок `pledges`: сервис отдаёт их «как скидывались»
 * (createdAt asc), тем же порядком, что экран «что подарили».
 */
export function goalForGuest(
  goal: RoomGoal,
  pledges: readonly Pick<GoalPledge, "amount" | "cancelToken" | "guestName">[],
  options: { myTokens?: readonly string[] } = {},
): GuestGoalDto {
  const mineTokens = new Set(options.myTokens ?? []);
  const pledged = pledges.reduce(
    (sum, pledge) => (pledge.amount ? sum.add(pledge.amount) : sum),
    new Prisma.Decimal(0),
  );
  const mine = pledges.some((pledge) => mineTokens.has(pledge.cancelToken));
  const others = pledges
    .filter((pledge) => !mineTokens.has(pledge.cancelToken))
    .map((pledge) => pledge.guestName);

  return {
    title: goal.title,
    amount: goal.amount.toString(),
    currency: goal.currency,
    pledged: pledged.toString(),
    participants: pledges.length,
    percent: percentOf(pledged, goal.amount),
    mine,
    // ЕДИНСТВЕННОЕ место, где решается, кому видны имена. Не участвуешь —
    // имён нет вовсе, а не «есть, но скрыты разметкой».
    who: mine ? poolWho(others, { you: true }) : null,
  };
}

/**
 * Доля собранного целыми процентами. Считается на Decimal (никакого float:
 * CLAUDE.md), зажимается в 0…100 — перебор по цели рисовать полосой длиннее
 * самой полосы нечем, а «Собрано 140%» ничего не добавляет к «Собрано 100%».
 * Цель ноль или меньше в БД не заводится (схема ввода), но делить на неё
 * всё равно нельзя — честный 0.
 */
function percentOf(pledged: Prisma.Decimal, target: Prisma.Decimal): number {
  if (target.lessThanOrEqualTo(0)) return 0;
  const raw = pledged.div(target).mul(100).toDecimalPlaces(0, Prisma.Decimal.ROUND_DOWN).toNumber();
  return Math.min(100, Math.max(0, raw));
}
