//
// ОТКУДА. Приёмка владельца 11.08.2026: «он просто что-то жмёт и вынужден
// каждый раз выходить в комнату». Выбор интерьера и выбор света делались
// вслепую по плиткам в 56 px, и человек уходил проверять результат в комнату.
//
// ГЛАВНОЕ ПРАВИЛО, РАДИ КОТОРОГО ЗАВЕДЁН ЭТОТ МОДУЛЬ: **превью показывает
// ВЫБРАННОЕ, а комнату меняет только «Переехать»**. Смена интерьера двигает
// вещи между полками — где полки совпадут, вещи останутся, остальные переедут
// в «Что угодно», — и делать это по тапу нельзя. Поэтому у экрана два разных
// значения: `currentPreset` (что стоит в комнате, приезжает с сервера) и
// `selected` (что человек смотрит, живёт в состоянии страницы). Кадр берёт
// второе, комната — первое, и `pending` честно говорит, что они разошлись.
//
// Модуль намеренно чистый: ни React, ни серверных действий. Иначе «а точно
// превью не трогает комнату?» проверялось бы прокликиванием.
import type { NativeTimeOfDay } from "@/components/scene/grading";

/**
 * Всё, что кадру нужно знать про интерьер: чем его показать и от какого
 * РОДНОГО времени суток считать грейдинг. Родное время — свойство фотографии
 * (четыре базы из десяти сняты ночью), и превью обязано считать от него же,
 * что и комната: иначе выбор «по картинке» показывает одно, а комната
 * становится другой (тикет 107).
 */
export type PreviewCard = {
  id: string;
  imageUrl: string;
  tod: NativeTimeOfDay;
};

/**
 * Карточка интерьера целиком: то, чем его показывает кадр (`PreviewCard`),
 * плюс то, чем его называет и красит лента. Форма та же, что в онбординге
 * (тикет 01); сам компонент онбординга не переиспользуем — там полноэкранный
 * флоу со своим сабмитом.
 *
 * ЖИВЁТ ЗДЕСЬ, А НЕ В `settings-sections.tsx`, с тикета 181: карточку читают
 * трое — лента, кадр и страница, — и класть её в файл секций значило бы, что
 * кадр импортирует секции ради типа. `PresetCard` расширяет `PreviewCard`, а
 * не повторяет его поля: разойдись они, кадру нечего было бы показать.
 */
export type PresetCard = PreviewCard & {
  name: string;
  sex: "F" | "M";
  accent: string;
  ink: string;
};

export type PreviewState<C extends PreviewCard> = {
  /** Интерьер, который показывает кадр. `null` — показывать нечего. */
  shown: C | null;
  /** Показанный интерьер выбран, но в комнате ещё не стоит. */
  pending: boolean;
};

/**
 * Кадр показывает выбранное; если выбранного нет в списке — то, что стоит в
 * комнате.
 *
 * ИСКАТЬ ОБЯЗАТЕЛЬНО ПО ПОЛНОМУ СПИСКУ, а не по отфильтрованной ленте:
 * переключатель заготовки полок («женская/мужская/все») прячет часть карточек,
 * и комната запросто оказывается среди спрятанных — своя же комната пропала бы
 * из кадра от переключения соседнего тумблера.
 */
export function previewOf<C extends PreviewCard>(
  cards: readonly C[],
  currentPreset: string,
  selected: string,
): PreviewState<C> {
  const shown =
    cards.find((card) => card.id === selected) ??
    cards.find((card) => card.id === currentPreset) ??
    null;
  return { shown, pending: shown !== null && shown.id !== currentPreset };
}
