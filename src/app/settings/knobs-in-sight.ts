// тикета 228: «когда мы спускаемся ниже по настройкам (гораздо ниже), мы уже
// поработали с комнатой и светом, нам не нужна комната сверху, там не на что
// смотреть».
//
// ЧТО ЗДЕСЬ ЗА ВОПРОС. Тикет 228 запер липкость в её разделе, и это правда:
// дальше блока «Интерьер + Свет» кадр не уезжает. Но последние 265 px пути он
// едет ОДИН — обе ручки к этому времени уже за спиной кадра, а треть телефона
// всё ещё занята комнатой, под которой стоят «О себе» и «Адрес комнаты».
// Значит берег у липкости неверный: смысл её ровно один — «крутишь свет,
// видишь комнату», — и кончаться она обязана вместе с РУЧКАМИ, а не вместе с
// разделом. Между кадром и ручками лежит лента интерьеров в 580 px, поэтому
// сами по себе эти два берега и разъехались.
//
// ПОЧЕМУ ЗДЕСЬ СКРИПТ. CSS не умеет «липни, пока виден ДРУГОЙ элемент»: у
// `sticky` берег ровно один — родитель. Наблюдатель пересечения самый дешёвый
// способ спросить про чужую видимость: ни слушателя прокрутки, ни замеров на
// каждый кадр. Нет наблюдателя — не делаем ничего: док остаётся липким
// по-старому, то есть хуже, чем сейчас, не станет.
//
// ГЛАВНОЕ ЧИСЛО — ВЫСОТА КАДРА, И ОНА НЕ КОНСТАНТА. Ручку не видно не с верха
// экрана, а с НИЗА КАДРА: док непрозрачный и висит на `top: 0`, ручки уезжают
// ему за спину. Замер тикета 228 на 375×812 говорит это числом: нижняя ручка
// пропадает на 962 px прокрутки, а её низ лежит на 1205.7 — ровно на 243.7
// ниже, и 243.7 есть высота дока. Проверка: до низа блока от неё остаётся 20.9
// px, то есть `p-5` секции с рамкой; отмеряй мы от верха экрана — там осталось
// бы 264.6, чему в разметке взяться неоткуда.
//
// Отсюда же цена ошибки: с нулевым полем наблюдатель отпустил бы кадр на
// 1205.7, за 21 px до того, как он уедет сам. Глазами такую починку не увидеть
// — то есть её бы и не было.
//
// Высота берётся ЗАМЕРОМ, а не числом: на широком экране кадр другой (289.7
// против 208.9), да и поворот телефона её меняет.

/** Ровно то, что наблюдатель рассказывает про блок ручек. */
export type KnobsSighting = {
  readonly isIntersecting: boolean;
  readonly boundingClientRect: { readonly bottom: number };
};

/**
 * Поля наблюдателя: видимое начинается под кадром, а не под верхом экрана.
 * Верхнее поле отрицательное — оно ОПУСКАЕТ верхнюю кромку зоны видимости на
 * высоту дока; остальные три стороны на месте.
 */
export function sightMargin(frameHeight: number): string {
  return `-${Math.max(0, Math.round(frameHeight))}px 0px 0px 0px`;
}

/**
 * Видно ли ручки — то есть обязан ли кадр липнуть.
 *
 * «Не пересекается» бывает ДВУХ РОДОВ, и путать их нельзя: ручки могут быть
 * ещё ВПЕРЕДИ (человек листает ленту интерьеров, до света не дошёл — кадр
 * обязан липнуть, ради ленты он и заведён) или уже ПОЗАДИ (ушли кадру за
 * спину — липнуть незачем). Различает их низ блока: пока он ниже кромки
 * видимого, ручки впереди.
 */
export function knobsInSight(sighting: KnobsSighting, frameHeight: number): boolean {
  return sighting.isIntersecting || sighting.boundingClientRect.bottom > frameHeight;
}

/**
 * Завести наблюдателя на БЛОКЕ РУЧЕК (не на странице и не на самом кадре) и
 * рассказывать про их видимость, пока не позовут возврат.
 *
 * Высота кадра приходит функцией, а не числом: она меряется в момент, когда
 * наблюдатель заводится, и заново — на изменение окна. `rootMargin` задаётся
 * один раз при создании, менять его нечем, поэтому поворот телефона и переход
 * через `lg` пересоздают наблюдателя целиком.
 *
 * @returns снять наблюдение (и слушателя окна вместе с ним)
 */
export function watchKnobs(
  knobs: Element,
  frameHeight: () => number,
  tell: (inSight: boolean) => void,
): () => void {
  const Watcher = globalThis.IntersectionObserver;
  // Старый браузер: молчим. Молчание оставляет док липким по-старому —
  // поведение тикета 228, и оно рабочее.
  if (typeof Watcher !== "function") return () => {};

  let watcher: IntersectionObserver | null = null;

  const start = () => {
    const frame = frameHeight();
    watcher = new Watcher(
      (entries) => {
        // Пачка приходит в порядке событий: последнее и есть «сейчас».
        const now = entries.at(-1);
        if (now) tell(knobsInSight(now, frame));
      },
      { rootMargin: sightMargin(frame) },
    );
    watcher.observe(knobs);
  };

  const again = () => {
    watcher?.disconnect();
    start();
  };

  start();
  const view = typeof window === "undefined" ? null : window;
  view?.addEventListener("resize", again);

  return () => {
    watcher?.disconnect();
    watcher = null;
    view?.removeEventListener("resize", again);
  };
}
