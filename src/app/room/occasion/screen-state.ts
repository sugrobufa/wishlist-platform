//
// ЧТО СЛУЧИЛОСЬ. Владелец нажал в комнате тихую строку «Праздник прошёл —
// посмотри, что подарили» и попал на экран с заголовком «Праздник ещё
// впереди»: «Ничего абсолютно не понятно что происходит на этой форме».
// Экран смотрел ТОЛЬКО на существование итога — нет итога, значит «впереди», —
// и состояние «праздник наступил, а итог не открыт» молча слилось с «праздник
// впереди». В жизни состояний три, и третье как раз то, ради которого на экран
// и приходят: дело есть, но оно ещё не сделано.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Выбор состояния и то, чем каждое состояние говорит, —
// одна таблица, а не четыре ветки, расставленные по разметке. Разметка её
// читает, тест проверяет её же; разъехаться им не через что. Данные приезжают
// готовыми из `services/occasions` (`summary` / `due` / `next`) — своей
// арифметики праздника здесь нет и быть не должно, иначе поверхности разойдутся
// снова, ровно тем же способом.
//
// Модуль намеренно без React и без БД: чистая функция и таблица ключей.

/** Что именно происходит с праздником этой комнаты прямо сейчас. */
export type OccasionScreenState =
  /** Итог открыт: имена уже раскрыты, экран показывает подарки. */
  | "summary"
  /** Праздник НАСТУПИЛ, итога нет — то самое третье состояние. */
  | "due"
  /** Праздник впереди: дата известна, ждать до неё. */
  | "next"
  /** Дня рождения нет вовсе: ни итога, ни «когда он пройдёт». */
  | "noDate";

/** Ровно те поля вида, которыми состояние и определяется. */
export type OccasionScreenInput = {
  summary: unknown | null;
  due: string | null;
  next: string | null;
};

/**
 * Состояние экрана по виду из сервиса. Порядок ответов — приоритет:
 * открытый итог старше наступившего праздника (он и есть его результат),
 * наступивший старше будущего (иначе повторится баг 216).
 */
export function occasionScreenState(view: OccasionScreenInput): OccasionScreenState {
  if (view.summary) return "summary";
  if (view.due) return "due";
  if (view.next) return "next";
  return "noDate";
}

/** Чем состояние говорит: ключи словаря `Occasion.*` и наличие элементов. */
export type OccasionScreenShape = {
  /** Ключ заголовка; null — заголовок собирает ветка итога (дата + число подарков). */
  title: "dueTitle" | "notClosedTitle" | null;
  /** Ключ подсказки под заголовком; null — у ветки итога свои строки. */
  hint: "dueHint" | "notClosedHint" | "notClosedNoDate" | null;
  /** Показать дату ближайшего праздника строкой `nearestLine` — как в комнате. */
  nearest: boolean;
  /**
   * Тон ручного закрытия (тикет 217): «полоса света» — только когда дело есть
   * прямо сейчас; впереди праздника дорога остаётся, но перестаёт гореть
   * («какой сценарий, когда пропадает эта кнопка, или она будет гореть год до
   * следующего праздника? Так не надо»). null — итог открыт, закрывать нечего.
   */
  close: "loud" | "quiet" | null;
  /** Тихая ссылка в настройки: назвать день рождения. */
  settings: boolean;
};

/** ЕДИНСТВЕННОЕ место, где записано, чем говорит каждое состояние. */
export const OCCASION_SCREEN: Record<OccasionScreenState, OccasionScreenShape> = {
  summary: { title: null, hint: null, nearest: false, close: null, settings: false },
  due: { title: "dueTitle", hint: "dueHint", nearest: false, close: "loud", settings: false },
  next: {
    title: "notClosedTitle",
    hint: "notClosedHint",
    nearest: true,
    close: "quiet",
    settings: false,
  },
  noDate: {
    title: "notClosedTitle",
    hint: "notClosedNoDate",
    nearest: false,
    close: "quiet",
    settings: true,
  },
};
