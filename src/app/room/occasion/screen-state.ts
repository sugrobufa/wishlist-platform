// ЧЕТЫРЕ СОСТОЯНИЯ ЭКРАНА «ЧТО ПОДАРИЛИ», А НЕ ДВА (тикет 216, приёмка
// 13.08.2026; наполнение — словами пакета 48, тикет 219).
//
// ЧТО СЛУЧИЛОСЬ. Владелец нажал в комнате тихую строку «Праздник прошёл —
// посмотри, что подарили» и попал на экран с заголовком «Праздник ещё
// впереди»: «Ничего абсолютно не понятно что происходит на этой форме».
// Экран смотрел ТОЛЬКО на существование итога — нет итога, значит «впереди», —
// и состояние «праздник наступил, а итог не открыт» молча слилось с «праздник
// впереди». В жизни состояний четыре, и то, ради которого на экран и приходят,
// как раз третье: дело есть, но оно ещё не сделано.
//
// ИМЕНА СОСТОЯНИЙ. У дизайна (`handoff/round48/occasion.json`) они зовутся
// `DUE · OPEN · AHEAD · NO_DATE`, у нас — `due · summary · next · noDate`.
// Соответствие один в один, переезда ключей нет: переименование дало бы ноль
// (правило раунда 43), а сверка с контрактом идёт по этому комментарию.
//
//   OPEN    → summary  · итог открыт, имена раскрыты
//   DUE     → due      · праздник наступил, итога нет — ПОРОГ
//   AHEAD   → next     · праздник впереди — ОЖИДАНИЕ
//   NO_DATE → noDate   · даты нет вовсе — итога не будет никогда
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Выбор состояния и то, чем каждое состояние говорит, —
// одна таблица, а не четыре ветки, расставленные по разметке. Разметка её
// читает, тест проверяет её же; разъехаться им не через что. Данные приезжают
// готовыми из `services/occasions` (`summary` / `due` / `next` / `takenTotal`) —
// своей арифметики праздника здесь нет и быть не должно, иначе поверхности
// разойдутся снова, ровно тем же способом.
//
// Модуль намеренно без React и без БД: чистая функция и таблица ключей.

/** Что именно происходит с праздником этой комнаты прямо сейчас. */
export type OccasionScreenState =
  /** OPEN: итог открыт, имена уже раскрыты, экран показывает подарки. */
  | "summary"
  /** DUE: праздник НАСТУПИЛ, итога нет — тот самый порог. */
  | "due"
  /** AHEAD: праздник впереди, дата известна, ждать до неё. */
  | "next"
  /** NO_DATE: дня рождения нет вовсе: ни итога, ни «когда он пройдёт». */
  | "noDate";

/** Ровно те поля вида, которыми состояние и определяется. */
export type OccasionScreenInput = {
  summary: unknown | null;
  due: string | null;
  next: string | null;
};

/**
 * Состояние экрана по виду из сервиса. Порядок ответов — приоритет:
 * открытый итог старше наступившего праздника (он и есть его результат),
 * наступивший старше будущего (иначе повторится баг 216).
 */
export function occasionScreenState(view: OccasionScreenInput): OccasionScreenState {
  if (view.summary) return "summary";
  if (view.due) return "due";
  if (view.next) return "next";
  return "noDate";
}

/**
 * Полоса света состояния: слово, подпись под ней и куда она ведёт.
 *
 * `open` — раскрыть итог прямо здесь (порог). Стрелки у неё нет: перехода не
 * происходит, раскрытие случается на этом же экране (`loud.noArrow`).
 * `date` — ЕДИНСТВЕННЫЙ случай, где громкое зовёт не к итогу, а к дате:
 * у комнаты без даты итога не будет никогда, и настройки — это место, тогда
 * как человеку нужно действие.
 */
export type OccasionLoud =
  | { key: "openButton"; hint: "openOnceHint"; action: "open" }
  | { key: "noDateButton"; hint: "noDateButtonHint"; action: "date" };

/** Чем состояние говорит: ключи словаря `Occasion.*` и наличие элементов. */
export type OccasionScreenShape = {
  /** Заголовок; null — его собирает ветка итога (дата + число подарков). */
  title: "dueTitle" | "aheadTitle" | "noDateTitle" | null;
  /** Строка под заголовком; `dueLead` несёт в себе счётчик забранного. */
  lead: "dueLead" | "aheadHint" | "noDateHint" | null;
  /** Вторая строка объяснения; есть только у комнаты без даты. */
  aside: "noDateWorks" | null;
  /**
   * Блок «Что случится по нажатию» — подпись `dueWhatOverline` и три строки.
   * ПРЕДУПРЕЖДЕНИЕ СТОИТ ДО НАЖАТИЯ, и в этом весь смысл: раньше про
   * необратимость говорила строка `hint`, то есть уже после раскрытия.
   * Диалога подтверждения при этом НЕТ (`warning.notADialog`): человек пришёл
   * именно за этим, стена была бы лишней.
   */
  whatHappens: readonly ["dueNames", "dueDone", "dueUnclaimed"] | null;
  /**
   * Где стоит счётчик забранного (`ownerTakenTotal`, тот же, что в комнате):
   * `lead` — числом внутри лида порога, `box` — отдельным блоком с подписью.
   * ЭТО ЕДИНСТВЕННОЕ ЧИСЛО, ВИДНОЕ ДО РАСКРЫТИЯ (инвариант №1): ни имени, ни
   * названия вещи, ни списка — иначе порог сам был бы раскрытием.
   */
  taken: "lead" | "box" | null;
  /** Полоса света состояния; null — громкого действия у него нет. */
  loud: OccasionLoud | null;
  /**
   * Тихая дорога к ручному итогу (`manualLink`) и её громкость. Стоит на одном
   * месте во всех состояниях: человек, нашедший её однажды, найдёт и в другом.
   * `quieter` — там, где громкое уже занято датой (комната без даты).
   */
  manual: "quiet" | "quieter" | null;
  /** Тихий выход «Не сейчас — в комнату»: только на пороге, рядом с полосой. */
  notNow: boolean;
  /** Тихая ссылка «Изменить дату — в настройках». */
  dateLink: boolean;
  /** Показать дату ближайшего праздника строкой `nearestLine` — как в комнате. */
  nearest: boolean;
  /**
   * ПРОЗРАЧНОСТЬ КАДРА СОБСТВЕННОЙ КОМНАТЫ В ШАПКЕ (пакет 49,
   * `headerPhoto.opacityByState`: DUE 1 · OPEN 1 · AHEAD 0.5 · NO_DATE 0.4).
   *
   * Приглушение и есть язык ожидания — «оно работает, только если есть что
   * приглушать», — поэтому кадр стоит во всех четырёх состояниях, а разное у
   * них только это число. Оно живёт полем таблицы, а не четырьмя ветками в
   * разметке: иначе состояние экрана снова описывалось бы в двух местах.
   */
  photo: 1 | 0.5 | 0.4;
  /**
   * Высота окна кадра, px (`headerPhoto.crop430.window`: 236, на пороге 250).
   * Порог выше на 14 px — единственное состояние, ради которого на экран и
   * приходят. Ширины из контракта здесь нет намеренно: кадр кроется
   * `object-fit: cover` (`cropSimple`), а числа кропа привязаны к 430 и на
   * 375 поехали бы.
   */
  photoHeight: 236 | 250;
};

