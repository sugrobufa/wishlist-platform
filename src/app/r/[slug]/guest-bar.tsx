import type { CSSProperties } from "react";
import Link from "next/link";
import { getTranslations } from "next-intl/server";
import { IconRoom, IconTreasury } from "@/components/icons";
import s from "@/components/tab-bar/tab-bar.module.css";
import { GuestBarOwnRoom } from "./guest-bar-own-room";

/**
 * НИЖНИЙ БАР ГОСТЯ (тикет 247, турн 56b + пакет 55 → guest-gaps.guestCta).
 *
 * ЗАЧЕМ ОН ЗАВЁЛСЯ. Призыв «Собрать свою» стоял строкой ПОД списком зон, и
 * владелец не смог до него добраться: «у гостя совсем не видно призыв создать
 * свою комнату, просто не дойти до этой кнопки». Дизайн подтвердил, что это не
 * случайность: «строка в потоке недостижима не случайно — она ниже списка зон,
 * а список растёт с числом полок». Решение турна 56b: третий элемент бара.
 *
 * А это единственная дорога из гостя в хозяина. Гость пришёл по ссылке, ничего
 * не создаёт и уйдёт — призыв обязан быть достижим, а не лежать за краем.
 *
 * ПОЧЕМУ СВОЙ КОМПОНЕНТ, А НЕ `TabBar`. У хозяйки пять мест и активная вкладка
 * из `TabKey`; у гостя мест три, «Добавить» нет вовсе (в чужую комнату вещь не
 * положишь), а третье место — дорога ИЗ комнаты, а не по ней. Общими остались
 * стили: полоса, высота и отступы у бара один раз посчитаны контрактом, и
 * заводить им вторые числа значило бы развести две полосы на одном экране.
 *
 * БАР СЕРВЕРНЫЙ, А ТРЕТЬЕ МЕСТО — КЛИЕНТСКОЕ (тикет 253). Оно зависит от того,
 * КТО смотрит («есть ли у зрителя своя комната»), а страница /r/{slug}
 * кэшируется целиком и сессии не читает — инвариант №7. В клиент уехало РОВНО
 * одно место (`guest-bar-own-room.tsx`) на уже существующем некэшируемом
 * канале «занято»; полоса, имя хозяйки и брони остаются серверными.
 *
 * СЛОВА ПЕРВЫХ ДВУХ МЕСТ ВРЕМЕННЫЕ, И ЭТО НАЗВАНО ВСЛУХ. Турн 56b требует
 * притяжательных — «Комната Кати», «Её сокровищница»: «притяжательное в первом
 * элементе бара обязательно, оно и есть напоминание». Ключей под них в пакете
 * нет ни одного, а сочинять их самим нельзя вдвойне: «Её» — род человека,
 * которого мы не знаем. Пока стоят нейтральные слова хозяйкиного бара, и
 * притяжательные запрошены письмом; приедут — сменятся только строки.
 */
export async function GuestBar({
  roomHref,
  ownerName,
  accent,
  ink,
}: {
  roomHref: string;
  /** Имя хозяйки для первого пункта — «Комната Кати». */
  ownerName: string;
  accent: string;
  ink: string;
}) {
  const t = await getTranslations("TabBar");
  const tGuest = await getTranslations("GuestRoom");
  const tBookings = await getTranslations("MyBookings");

  return (
    <nav
      aria-label={t("tabsAria")}
      className={`${s.numbers} ${s.bar}`}
      style={{ "--tb-accent": accent, "--tb-ink": ink } as CSSProperties}
    >
      {/* ПЕРВЫЙ ПУНКТ НАЗЫВАЕТ ИМЕНЕМ, И ЭТИМ РЕШЁН РОД (пакет 56, турн 62b).
          Турн 56b требовал притяжательного — «Комната Кати», не «Комната», —
          а «Её сокровищница» требовала бы РОД человека, которого продукт не
          знает и знать не должен: пол у нас предустановка комнат, а не свойство
          человека. Дизайн согласился с отказом своими словами: «хранить его
          ради подписи значит завести первое место, где продукт что-то
          утверждает о человеке». Имя снимает вопрос без нового поля.

          Склонений продукт не знает — «Комната Катя» цена, которую мы уже
          платим в заголовке страницы и в «Мои подарки». Режется ТОЛЬКО имя:
          слово «Комната» уцелевает всегда. */}
      <Link href={roomHref} className={`pressable ${s.slot} ${s.slotActive}`}>
        <IconRoom size={22} />
        <span className={s.tabName}>{tGuest("tabRoom", { name: ownerName })}</span>
      </Link>

      {/* ВИТРИНЫ В БАРЕ НЕТ НИ В ОДНОМ РЕЖИМЕ, и это правка НАШЕЙ сборки.
          Мы поставили её сюда, собирая бар по рисунку турна 61d, — а рисунок
          спорил с инвариантом самого дизайна: знак витрины живёт в углу кадра,
          и две дороги в одно место сняты турном 36d. Его слово: «нарисовал я,
          вопреки собственному инварианту; если рисунок спорит с уставом —
          виноват рисунок». Второй пункт принадлежит ГОСТЮ — его брони. */}
      <Link href="/my-bookings" className={`pressable ${s.slot}`}>
        <IconTreasury size={22} />
        {tBookings("title")}
      </Link>

      {/* ТРЕТЬЕ МЕСТО — ДОРОГА ИЗ КОМНАТЫ, И ОНА У ДВУХ ЗРИТЕЛЕЙ РАЗНАЯ
          (тикет 253). У кого своей комнаты нет — призыв «Собрать свою» со
          знаком плюс, как было; у кого есть — дорога домой на /room. Развилка
          знает зрителя, а страница кэшируется целиком и сессии не читает, —
          поэтому место уехало в клиентский кусок на некэшируемом канале
          «занято», а бар остался серверным. `ctaHint` сюда по-прежнему НЕ едет
          — в баре место названию (турн 61d). */}
      <GuestBarOwnRoom />
    </nav>
  );
}
