"use client";

// ТРЕТЬЕ МЕСТО ГОСТЕВОГО БАРА (тикет 253, приёмка 16.08.2026): «если я
// просматриваю страницу в качестве гостя и допустим имею свою страницу, то как
// мне это увидеть на странице гостя и быстро перейти к себе?».
//
// Место звало «Собрать свою» и вело на первый экран воронки ВСЕГДА — человеку с
// готовой комнатой продукт предлагал собрать её заново, а дороги к себе не
// давал вовсе: ни в баре, ни в шапке. Теперь оно переключается по флагу
// `hasOwnRoom`: нет своей комнаты (или зритель аноним) — призыв, как был; есть —
// дорога домой на /room. Хозяину ЭТОЙ комнаты (тикет 250) она нужна тем более:
// «себе подарить нельзя» — значит уходить ему отсюда некуда, кроме как к себе.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ КЛИЕНТСКИЙ КОМПОНЕНТ, А НЕ ПРОП БАРА. Ответ зависит от того,
// КТО смотрит, а страница /r/{slug} кэшируется целиком и сессии не читает
// (инвариант №7, шапка page.tsx) — на сервере такой развилки не нарисовать, не
// сломав ISR. Флаг приезжает уже существующим некэшируемым каналом «занято»
// (booking-context): второго запроса и нового роута ради одного места не
// заводится. Тот же приём, что у соседей — «Сокровищница» в углу кадра
// (booking/hall-link) и «Мои подарки · N» (booking/my-bookings-link); в клиент
// уезжает одно место бара, а не бар и не страница.
//
// ДО ОТВЕТА КАНАЛА СТОИТ ПРИЗЫВ, а не пустота: гостей без своей комнаты
// большинство, и призыв последнего экрана воронки не имеет права мигнуть и
// пропасть — ровно за его достижимость тикет 247 и завёл этот бар.
import Link from "next/link";
import { useTranslations } from "next-intl";
import { IconPlus, IconRoom } from "@/components/icons";
import { useGuestBooking } from "./booking/booking-context";
import s from "@/components/tab-bar/tab-bar.module.css";

export function GuestBarOwnRoom() {
  const t = useTranslations("GuestRoom");
  const { hasOwnRoom } = useGuestBooking();

  // ЗНАК «ПЛЮС» ЖИВЁТ ТОЛЬКО В ПРИЗЫВЕ. Он выбран за обещание нового: «дом
  // занят „Комнатой", человек читается как „профиль", плюс говорит „появится
  // новое"» (турн 61d). Человеку с готовой комнатой это обещание — ложь, и
  // ниже его нет.
  if (!hasOwnRoom) {
    return (
      <Link href="/" className={`pressable ${s.slot}`}>
        <IconPlus size={22} strokeWidth={2.1} />
        {t("cta")}
      </Link>
    );
  }

  return (
    // Знак комнаты — тот же, что у первого места, и это не двоение: там арка
    // называет ЧУЖУЮ комнату (по имени хозяйки), здесь — свою. Своих знаков
    // набор не допускает вовсе (icons.tsx: «рисовать свои варианты нельзя»).
    // Тёплая точка-лампа НЕ горит: по 25a она горит только у активного места,
    // а активно здесь первое — человек стоит в комнате хозяйки, а не в своей.
    <Link href="/room" className={`pressable ${s.slot}`}>
      <IconRoom size={22} dot={false} />
      {t("ctaMine")}
    </Link>
  );
}
