"use client";

// «Сколько в зоне ещё свободно» — гостевая половина счётчика зоны (тикет 124,
// инвариант №8 в новой редакции).
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ КЛИЕНТСКИЙ УЗЕЛ, А НЕ ПОЛЕ СВОДКИ. Второе число —
// производное от БРОНЕЙ, а сводка зоны складывается внутри кэша комнаты
// (services/guest-room) и уезжает в полностраничный ISR. Хозяйка открывает
// свою же ссылку и получает тот же кэшированный HTML: «7 свободно» при восьми
// вещах сказало бы ей поимённо, что одну с этой полки забрали, — ровно то,
// что запрещает инвариант №1 («ни в API, ни в кэше»).
//
// Поэтому число считает ЭКРАН, из некэшируемого канала «занято» (тикет 08) —
// тем же приёмом, что «Мои подарки · N» и «7 подарков ещё свободны». Хозяйке
// тот же канал отвечает пустотой (services/bookings.takenForOwner), а её
// собственная комната этот узел не рисует вовсе: у неё в том же месте стоит
// «N вещей» (ZoneGrid.zoneCounts).
//
// Идентификаторы вещей зоны приходят пропом из кэшируемой страницы, и это
// безопасно: они и так лежат в её разметке — из них собраны сами плитки.
// Следов броней в них нет, брони живут только в наборе `taken`.
import { useTranslations } from "next-intl";
import { zoneCounterLine } from "@/components/scene/zone-counter";
import { useGuestBooking } from "./booking-context";

export type GuestZoneFreeProps = {
  /** Сколько вещей в зоне — `ZoneSummaryDto.count`, посчитан сервером. */
  total: number;
  /** Идентификаторы этих вещей: из них вычитается набор занятых. */
  itemIds: readonly string[];
};

export function GuestZoneFree({ total, itemIds }: GuestZoneFreeProps) {
  const t = useTranslations("Scene");
  const { taken } = useGuestBooking();

  // Пока канал не ответил, `taken` пуст и свободны все — то же, что уже
  // сказала кэшированная страница. Мигания «было 4, стало 3» это не создаёт:
  // строка меняется один раз, вместе с бирками вещей.
  let free = 0;
  for (const id of itemIds) {
    if (!taken.has(id)) free += 1;
  }

  const line = zoneCounterLine(total, free);
  return <>{t(line.key, line.values)}</>;
}
