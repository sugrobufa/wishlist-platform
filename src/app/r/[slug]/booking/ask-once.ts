// «Спрашиваем ровно один раз» (тикет 38, турн 12c) — правило отдельно от
// разметки, чтобы его можно было проверить тестом (ask-once.test.ts), а не
// прокликиванием брони в приватном окне.
//
// ПОЧЕМУ ХРАНИЛИЩЕ БРАУЗЕРА, А НЕ СЕРВЕР. Это вежливость, а не право доступа:
// цена ошибки — лишний вопрос, а не утечка. Серверу для такой отметки
// понадобилось бы опознавать анонимного гостя между визитами — то есть ровно
// то, чего продукт не делает (инвариант №4: людей мы не собираем).

/** Отметка «уже спрашивали». Версия в ключе — чтобы спросить снова можно было
 *  осознанным решением (сменив её), а не молча починив баг у всех сразу. */
export const ROOM_OFFER_ASKED_KEY = "wl.room-offer.v1";

/** Ровно то, что нам нужно от localStorage, — и ничего больше. */
export type AskStore = Pick<Storage, "getItem" | "setItem">;

/**
 * localStorage браузера или `null`. Обращение к нему само по себе может
 * бросить (приватное окно, запрет хранения в настройках) — поэтому в try.
 */
export function browserAskStore(): AskStore | null {
  try {
    return typeof window === "undefined" ? null : window.localStorage;
  } catch {
    return null;
  }
}

/**
 * Спрашивали ли уже. Хранилища нет или оно молчит — считаем, что НЕ
 * спрашивали: единственный источник новых хозяек важнее аккуратности отметки,
 * а худшее, что случится, — вопрос повторится в другом окне.
 */
export function alreadyAsked(store: AskStore | null): boolean {
  if (!store) return false;
  try {
    return store.getItem(ROOM_OFFER_ASKED_KEY) !== null;
  } catch {
    return false;
  }
}

/**
 * Запомнить, что спросили. Зовётся в момент ПОКАЗА, а не ответа: «Потом» и
 * молчание для нас одно и то же — второй раз мы не спрашиваем ни в том, ни в
 * другом случае.
 */
export function rememberAsked(store: AskStore | null): void {
  if (!store) return;
  try {
    store.setItem(ROOM_OFFER_ASKED_KEY, "1");
  } catch {
    // запрет на хранение — не повод ломать лист брони
  }
}
