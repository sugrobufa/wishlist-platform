// Приветственный блок гостевой комнаты (тикет 38, турн 12b) — счёт дней до
// праздника. Модуль намеренно без React и без БД: правило «через сколько
// дней» проверяется тестом (welcome.test.ts), а не прокликиванием комнаты.
//
// ПОЧЕМУ ОТДЕЛЬНО ОТ СЕРВИСА. `GuestRoomView.occasionDate` — свойство
// комнаты, а «через 12 дней» — свойство СЕГОДНЯШНЕГО ДНЯ. Смешай их в одном
// месте — и число окажется в кэше комнаты, где оно протухнет на смене суток.
// Сервис отдаёт день, страница считает разницу при рендере.

/** Ровно то, что отдаёт сервис: календарный день без времени и без зоны. */
const ISO_DAY = /^\d{4}-\d{2}-\d{2}$/;

const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * Сколько полных суток осталось до праздника: 0 — сегодня, 1 — завтра.
 * `null` — даты нет, дата непонятная или праздник уже прошёл (тогда строки в
 * приветствии просто не будет: «праздник был 3 дня назад» гостю не нужно —
 * он пришёл выбирать подарок, а не сожалеть).
 *
 * Считается В UTC — тем же поясом, которым сервис отдаёт ближайший праздник
 * (полночь UTC, server/birthday.nextOccasion). Считать «сегодня» по поясу
 * машины значило бы получать разные числа на сервере и у гостя из другого
 * часового пояса — и разъезжаться с датой в письме-напоминании, которое
 * считает тем же UTC.
 */
export function daysUntilOccasion(occasionDate: string | null | undefined, now: Date): number | null {
  if (typeof occasionDate !== "string" || !ISO_DAY.test(occasionDate)) return null;
  const target = Date.parse(`${occasionDate}T00:00:00.000Z`);
  if (Number.isNaN(target)) return null;
  // Круг: несуществующий день (2026-02-31 разбором «переезжает» на 3 марта)
  // праздником не считается — то же правило, что в онбординге.
  if (new Date(target).toISOString().slice(0, 10) !== occasionDate) return null;

  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  const days = Math.round((target - today) / DAY_MS);
  return days < 0 ? null : days;
}
