"use client";

// Шкала желания ВВОДОМ — четыре огонька на целях 44 (тикет 124, раунд 29,
// `design/package/handoff/round29/task31.json` → addFormScale). Шаг между
// целями — 10, и ряд целиком 206 (тикет 225, пакет 49 → desire-scale-v2.json):
// ОДНО число на карточку, потому что форма и карточка делят этот компонент.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ КОМПОНЕНТ. Ввод степени живёт в двух местах: вторым вопросом
// формы добавления и правкой НА МЕСТЕ в карточке вещи у хозяйки. Правила у них
// одни («дефолта нет», «не скажу» законно, слово появляется при выборе), и
// разъехаться им нельзя: расхождение здесь не видно ни линту, ни типам — оно
// видно только человеку, который заполняет форму и не узнаёт её в карточке.
//
// ПРАВИЛА ДИЗАЙНА (task31.json → addFormScale), воплощаются здесь целиком:
// - `mandatory: НЕТ` — поле необязательное, «не скажу» остаётся законным
//   пустым: «принуждение убьёт шкалу»;
// - `form` — четыре огонька на целях 44, точка 14 px, слово ступени появляется
//   ПРИ ВЫБОРЕ, «не скажу» тихой кнопкой справа, **дефолта НЕТ**;
// - `devaluation` — «мечтаю у всего подряд» без дефолта не случается: каждый
//   огонёк это выбор, а слова ступеней держат лестницу. Поэтому ни одна
//   ступень не проставляется системой — ни здесь, ни в сервисе.
//
// ПУСТОЕ ПОЛОЖЕНИЕ УМЕЕТ НАЗЫВАТЬ СЕБЯ (тикет 215, приёмка 13.08). Слово
// ступени называет шкалу, только когда ступень выбрана; у вещи БЕЗ степени на
// экране оставались четыре серых кружка и «не скажу» — в форме их называет
// подпись сверху, а в карточке подписи нет. Поэтому у компонента есть
// необязательное `emptyLabel`: карточка передаёт его, форма не передаёт
// ничего. Пробел контракта дизайн признал своим (round48/desire-scale.json →
// `gapAdmitted`: «описал подписью ФОРМУ и забыл КАРТОЧКУ»).
//
// СЛОВО ЗАКРЫТО ПАКЕТОМ 48 (тикет 221). Карточка передаёт `ItemCard.desireEmpty`
// («не сказано, насколько хочется»), а не `AddItem.desireLabel`, как сутки
// стояло у нас: в форме шкала — ВОПРОС, в карточке — ОТВЕТ, и «не скажу» здесь
// законное значение, а не пустота. Компонента это не касается — слово приходит
// снаружи, и в этом весь смысл пропа: два места, два голоса, одна шкала.
//
// ПОЧЕМУ ЭТО RADIOGROUP НА ПЯТЬ ПОЛОЖЕНИЙ, А НЕ ЧЕТЫРЕ. «Не скажу» — такое же
// состояние поля, как и четыре ступени, и читалка обязана уметь в него
// вернуться. Начальное положение группы — именно оно, и это не «дефолт
// степени»: ни один огонёк не горит, пока по нему не нажали.
//
// СВЕЧЕНИЕ ПЕРЕЕХАЛО НА ПОСЛЕДНЮЮ ВЫБРАННУЮ СТУПЕНЬ (тикет 225, пакет 49 →
// `round49/desire-scale-v2.json` → layout.chosenGlow). Прежде здесь работало
// правило 36d — ореол только у «мечтаю», «мечта в этом продукте всегда
// подсвечена». Два правила спорят ровно на трёх ступенях из четырёх, и взята
// редакция round49 как свежая: свечение получает верхняя ГОРЯЩАЯ точка при
// любой степени. «Мечтаю» при этом не погашена — на 4 из 4 верхняя точка и
// есть «мечтаю»; изменилось не «светится ли она», а «светится ли она ОДНА»
// (и сам рецепт: 14/2 при .5 вместо 10 при .9). Показ у гостя (`DesireScale`)
// живёт по 36d по-прежнему: контракт 49 гостевую половину не упоминает.
import { useTranslations } from "next-intl";
import { DESIRE_STEPS } from "./desire-scale";
import s from "./desire-picker.module.css";

/** "#RRGGBB" + альфа → 8-значный hex (свечение выбранной — акцент с .5). */
function withAlpha(hex: string, alpha: number): string {
  const a = Math.round(alpha * 255)
    .toString(16)
    .padStart(2, "0");
  return `${hex}${a}`;
}

type DesirePickerProps = {
  /** 1–4 или `null` («не скажу»). Значения вне 1–4 читаются как пустое. */
  desire: number | null;
  /** Акцент комнаты «#RRGGBB» — им горят выбранные огоньки. */
  accent: string;
  /** Новое значение: ступень или `null`. Повторный тап по ступени её снимает. */
  onPick: (next: number | null) => void;
  disabled?: boolean;
  /**
   * СЛОВО ПУСТОГО ПОЛОЖЕНИЯ — на месте слова ступени, пока ни одна не выбрана
   * (тикет 215). Нужно там, где над шкалой подписи НЕТ: в карточке вещи без
   * степени человек видит четыре серых кружка и «не скажу», и назвать их
   * нечем — слово ступени, которое обычно это делает, там как раз молчит.
   * Карточка передаёт `ItemCard.desireEmpty` — не вопрос, а ответ (тикет 221).
   *
   * Форма добавления свойство не передаёт нарочно: над шкалой у неё уже стоит
   * `AddItem.desireLabel` своей строкой, и второй раз это то же самое слово.
   * Отсюда и необязательность — не «настройка вида», а два разных места.
   */
  emptyLabel?: string;
};

export function DesirePicker({ desire, accent, onPick, disabled, emptyLabel }: DesirePickerProps) {
  const t = useTranslations("AddItem");
  const value = desire != null && DESIRE_STEPS.includes(desire as 1 | 2 | 3 | 4) ? desire : null;

  return (
    <div className={s.picker}>
      <div className={s.steps} role="radiogroup" aria-label={t("desireLabel")}>
        {DESIRE_STEPS.map((step) => {
          const on = value != null && step <= value;
          return (
            <button
              key={step}
              type="button"
              role="radio"
              disabled={disabled}
              aria-checked={value === step}
              aria-label={t(`desire${step}`)}
              // Повторный тап по выбранной ступени возвращает пустое: дорога
              // назад из ошибочного тапа обязана быть, а «не скажу» рядом —
              // не всегда очевидный способ ею воспользоваться.
              onClick={() => onPick(value === step ? null : step)}
              className={`pressable ${s.step}`}
            >
              <span
                aria-hidden
                className={on ? `${s.flame} ${s.flameOn}` : s.flame}
                style={
                  on
                    ? {
                        background: accent,
                        // Свечение — у ПОСЛЕДНЕЙ ВЫБРАННОЙ ступени, то есть у
                        // верхней горящей точки (round49 → layout.chosenGlow).
                        // Цвет контракта — rgba(231,201,169,.5) — это акцент
                        // комнаты с .5: комната данные, и вписывать её цвет
                        // числом значило бы показать всем одну и ту же.
                        boxShadow:
                          step === value ? `0 0 14px 2px ${withAlpha(accent, 0.5)}` : undefined,
                      }
                    : undefined
                }
              />
            </button>
          );
        })}

        {/* «Не скажу» — тихая кнопка справа (task31.json → addFormScale.form).
            Стоит на экране ВСЕГДА, а не появляется после выбора: она и есть
            обещание «поле необязательное», ради которого шкалу подняли вторым
            вопросом. Акцентом не горит никогда — иначе пустое положение
            читалось бы выбранным по умолчанию, а дефолта у шкалы нет. */}
        <button
          type="button"
          role="radio"
          disabled={disabled}
          aria-checked={value === null}
          onClick={() => onPick(null)}
          className={value === null ? `pressable ${s.unset} ${s.unsetOn}` : `pressable ${s.unset}`}
        >
          {t("desireUnset")}
        </button>
      </div>

      {/* Слово ступени появляется ПРИ ВЫБОРЕ. На пустом на его месте стоит
          подпись `emptyLabel`, если её передали (тикет 215), — а не «не скажу»
          вторым голосом: оно уже написано кнопкой рядом, и повторять его
          значило бы сказать дважды одно и то же.

          Строка при этом есть в обоих положениях, и это вторая польза подписи:
          выбор ступени больше не двигает раскладку карточки на высоту строки.
          Без подписи (форма добавления) поведение прежнее — пусто и пусто.

          МЕСТО У СЛОВА СПРАВА, А ТОН РАЗНЫЙ (round49 → layout.word, wordTone):
          выбрано — 500 12.5, пусто — 400 12, оба при .6. Класс здесь ровно
          поэтому: два тона это не «вид», а два ЗНАЧЕНИЯ одного поля. */}
      {(value !== null || emptyLabel !== undefined) && (
        <p className={value !== null ? `${s.word} ${s.wordChosen}` : s.word}>
          {value !== null ? t(`desire${value}`) : emptyLabel}
        </p>
      )}
    </div>
  );
}
