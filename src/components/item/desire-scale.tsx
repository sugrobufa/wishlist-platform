// Степень желания — четыре огонька (тикет 125, турн 36d).
//
// ЗАЧЕМ. Поле `desire` (1–4) заполняется при добавлении и в правке, лежит в
// базе и доезжает до гостя ОБОИМИ DTO — и не рисовалось ни одним компонентом.
// Владелец: «У нас есть при добавлении вещи его степень желания — нигде в
// карточке у гостя и хозяйки я этого не видел. Почему?» Потому что показ никто
// не собрал: проводка была целой до последнего шага. Этот файл — тот шаг.
//
// ВИД ОДИН (36d), числами доски: четыре огонька 6 px с шагом 5, у цены и со
// словом ступени рядом.
//
// ВТОРОГО ВИДА БОЛЬШЕ НЕТ (тикет 161). Был «row» — 5 px без слова, — и завёлся
// он ради строки списка зоны. Строку у него забрал сам дизайн: контракт
// `handoff/zone-row.json → form.wishDot` оставил строке ОДНУ верхнюю ступень
// точкой 5 px («четыре огонька в строке 52 съедают имя; лестница целиком живёт
// в сетке и в карточке»), и точку эту рисует `zone-row.tsx` своим `.dot`.
// После тикета 152 у варианта не осталось ни одного потребителя в продукте, а
// дома для «5 px без слова» не осталось и в языке продукта: оба места полной
// лестницы, названные контрактом, — это вид карточки.
//
// Остальные правила:
// - заполненные — акцент комнаты, пустые — .2;
// - на «мечтаю» (4 из 4) последний огонёк светится: единственная ступень с
//   ореолом. «Мечта в этом продукте всегда подсвечена»;
// - `desire = null` («не скажу») — шкалы нет ВОВСЕ: пустое не рисуется нулём;
// - в сокровищнице шкала не показывается: желание исполнено (проверка — в
//   вызывающей стороне, здесь такого знания нет);
// - гостю — тот же вид: он по шкале выбирает подарок;
// - в карточке ХОЗЯЙКИ показа нет вовсе — там ввод (`DesirePicker`, раунд 29).
//
// Слова — `AddItem.desire1–4` («пусть будет · хочется · очень хочется ·
// мечтаю»): шкала заполняется в добавлении и правке, там её словарь и живёт.
import { useTranslations } from "next-intl";
import s from "./desire-scale.module.css";

/** Ступеней ровно четыре — и в форме, и в показе (items.json → extraFields). */
export const DESIRE_STEPS = [1, 2, 3, 4] as const;

/** Верхняя ступень: «мечтаю». Только у неё огонёк с ореолом. */
export const DESIRE_DREAM = 4;

type DesireScaleProps = {
  /** 1–4; `null`/`undefined` — «не сказано». */
  desire: number | null | undefined;
  /** Акцент комнаты «#RRGGBB» — им горят заполненные огоньки. */
  accent: string;
  /**
   * ДВА ВИДА ВЕРНУЛИСЬ, И ВЕРНУЛ ИХ ДИЗАЙН (тикет 252, пакет 55 → desire-guest,
   * турн 61c). Тикет 161 снял второй вид правильно: у него не осталось ни
   * одного потребителя. Теперь потребитель есть, и это ПЛИТКА В СЕТКЕ — место,
   * где гость выбирает подарок и где подсказки не было вовсе.
   *
   *   card — 14 с шагом 10, со словом. Числа контракта: «у гостя это НЕ цель
   *          нажатия, поэтому шага 10 между целями 44 нет — огоньки рядом»;
   *   tile — точка 5 с шагом 4, без слова: «не влезает».
   */
  variant?: "card" | "tile";
};

/** "#RRGGBB" + альфа → 8-значный hex (ореол «мечтаю» — акцент с .9). */
function withAlpha(hex: string, alpha: number): string {
  const a = Math.round(alpha * 255)
    .toString(16)
    .padStart(2, "0");
  return `${hex}${a}`;
}

export function DesireScale({ desire, accent, variant = "card" }: DesireScaleProps) {
  const t = useTranslations("AddItem");
  const known = desire != null && DESIRE_STEPS.includes(desire as (typeof DESIRE_STEPS)[number]);

  /**
   * НА ПЛИТКЕ ПУСТОЕ СОСТОЯНИЕ РИСУЕТСЯ, В КАРТОЧКЕ — НЕТ, и это не
   * непоследовательность. Слово дизайна: «четыре контура — „хозяйка не
   * сказала" тоже ответ». В сетке гость сравнивает вещи взглядом, и дырка на
   * месте шкалы у одной из них читалась бы как «шкалы у этой нет», а не как
   * ответ. В карточке вещь одна, сравнивать не с чем, и пустая шкала была бы
   * шумом — там место занимает слово `ItemCard.desireEmpty`.
   *
   * Мусор из БД сюда же: рисовать «полшкалы» по неожиданному числу мы не
   * станем ни в одном из видов.
   */
  if (!known && variant === "card") return null;

  const word = known ? t(`desire${desire}`) : "";

  const filled = known ? (desire as number) : 0;

  return (
    <span className={variant === "tile" ? `${s.scale} ${s.tile}` : s.scale}>
      {/* Слово стоит рядом всегда — читалке его и хватает, поэтому огоньки от
          неё скрыты. Прежде здесь была развилка: безсловный вид отдавал шкале
          `role="img"` с подписью. Вида того больше нет (тикет 161). */}
      <span className={s.flames} aria-hidden>
        {DESIRE_STEPS.map((step) => (
          <span
            key={step}
            className={step <= filled ? `${s.flame} ${s.flameOn}` : s.flame}
            style={
              step <= filled
                ? {
                    background: accent,
                    boxShadow:
                      desire === DESIRE_DREAM && step === DESIRE_DREAM
                        ? `0 0 8px ${withAlpha(accent, 0.9)}`
                        : undefined,
                  }
                : undefined
            }
          />
        ))}
      </span>
      {variant === "card" && <span className={s.word}>{word}</span>}
    </span>
  );
}
