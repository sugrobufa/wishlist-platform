// Вид «вещь в сетке зоны» — структурный контракт ZoneGrid.
// Owner-DTO (src/server/dto/items) удовлетворяет ему как есть (зафиксировано
// компайл-проверкой в tests/items.dto.test.ts); guest-DTO тикета 07 — тоже:
// необязательные поля он может не отдавать (цена гостю приходит уже
// отфильтрованной по priceVisibility, для хозяйки видна всегда).

export type ZoneGridItem = {
  id: string;
  /**
   * Место вещи (тикет 124): false — комната, true — сокровищница. Поля
   * `state` больше нет: состояний у вещи не осталось. В сетку зоны витринная
   * вещь не приезжает вовсе — сервис её отфильтровал, — но ключ нужен формам
   * DTO, которые сетка принимает как есть.
   */
  inHall?: boolean;
  title: string;
  photoUrl: string | null;
  /** Демо-призрак: полупрозрачная плитка, бейдж «пример», не бронируется. */
  isDemo: boolean;
  note?: string | null;
  /** Вещь комнаты: цена строкой (Decimal), валюта ISO 4217, видимость цены. */
  price?: string | null;
  currency?: string | null;
  priceVisibility?: "ALL" | "FRIENDS" | "ME" | "NONE";
  /**
   * Вещь комнаты глазами гостя: где купить (тикет 37). Приезжает только из
   * guest-DTO — у хозяйки ссылка живёт в карточке вещи, а не на плитке
   * («бирка» и переход наружу — язык гостевого режима). От цены ключ НЕ
   * зависит (тикет 195): скрытая цена прячет число, а не путь к вещи.
   */
  shop?: { url: string; domain: string } | null;
  /**
   * Степень желания 1–4 («пусть будет … мечтаю»), `null` — «не скажу»
   * (тикет 125). Приходит из ОБОИХ DTO и показывается одинаково хозяйке и
   * гостю: в строке зоны — четырьмя огоньками без слова (турн 36d).
   */
  desire?: number | null;
  /** Вещь сокровищницы: подпись «Подарок {год} года · от {даритель}». */
  giverName?: string | null;
  receivedAt?: string | null;
  hidden?: boolean;
  /**
   * Когда вещь заведена — для чипа «по дате» на экране зоны (тикет 74, 29b).
   * Приходит из обоих DTO (owner и guest) и в виде не участвует: сортировка
   * пользуется им, плитка — нет.
   */
  createdAt?: string;
  /**
   * Услуга-впечатление (тикет 97): «Когда · Где · Годен до». Строки, а не
   * даты, — доска пускает «выходные» и «март». Зона `events` показывает их
   * строкой вместо плитки (тикет 115, доска 34d: «форму выбирает зона»).
   */
  eventWhen?: string | null;
  eventWhere?: string | null;
  validUntil?: string | null;
  /** Срок вышел — считает сервер (услуга уходит из «можно подарить»). */
  expired?: boolean;
};
