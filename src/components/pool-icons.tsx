/** Есть ли у пула свой значок. Пул `money` и зона без пула — нет. */
export function hasPoolIcon(pool: string | null | undefined): pool is PoolIconKey {
  return pool != null && pool in SHAPES;
}

/** Значок пула зоны. Молчит, если значка нет — вызывающий покажет букву. */
export function PoolIcon({ pool, ...props }: IconProps & { pool: string }) {
  if (!hasPoolIcon(pool)) return null;
  return <Icon24 {...props}>{SHAPES[pool]}</Icon24>;
}
