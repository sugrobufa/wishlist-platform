// Знаки в правом верхнем углу сцены — «Списком» и «Сокровищница»
// (тикеты 118 и 119, турн 36c).
//
// ЧТО БЫЛО. Оба входа стояли тихими пилюлями СО СЛОВОМ под оглавлением зон —
// у хозяйки (тикет 67) и у гостя (тикеты 77, 93). Владелец на приёмке 09.08:
// «Списком надо сделать не слово, а иконку и увести в правый верхний угол…
// Сокровищница уходит наверх в правый угол как у хозяина, так и у гостя».
// Дизайн прислал знаки (`handoff/icons/ui-list.svg`, `ui-treasury.svg`) и
// правило: 22 px на цели 44, плашка rgba(11,8,6,.55) с блюром, у обеих
// сторон одинаково. Слово осталось в `aria-label` и всплывающей подсказке —
// знак без слова обязан быть понятен сам, но читалке и мыши слово нужно.
//
// ГДЕ ОНИ ЖИВУТ. В ВЕРХНЕЙ ПОЛОСЕ (`.imm-rail-top`), рядом с именем комнаты:
// на телефоне выпадают из её потока в самый угол (12/14 по доске — там
// пусто), на десктопе встают её последним пунктом, справа от служебных
// ссылок. Отдельным слоем поверх на широком экране они легли бы прямо на
// этот ряд: он идёт от того же правого края и на той же высоте. Числа и обе
// ветки — globals.css → .imm-corner.
//
// РАСКЛАДКУ ЗНАКИ НЕ ДВИГАЮТ. Правый верх сцены — территория тикетов 42/45
// (immersive-layout.ts и его тест): там считается коробка кадра и цели
// нажатия всех 130 зон. Верхняя полоса лежит НА кадре и в эту формулу не
// входит — ровно как не входит постоянный таб-бар.
//
// ПРИ ОТКРЫТОЙ ЗОНЕ ЗНАКИ ОСТАЮТСЯ, и это не недосмотр: они часть верхней
// полосы, а полоса при наезде камеры не прячется — имя комнаты и тихий
// счётчик видны всё время. Прячутся другие вещи и по другой причине:
// подсказка «коснись зоны» врала бы (зона уже открыта), нить-позиция врала бы
// (в зоне кадр не панорамируется), а значок «поделиться» ложился НА лист
// вещей (тикет 121). Знаки в углу не врут и ни на что не ложатся.
import Link from "next/link";
import type { ReactNode } from "react";

/**
 * Размер знака в углу — 22 px на цели 44 (турн 36c). Число одно на обе
 * стороны: страницы берут его отсюда, а не набивают руками, иначе у хозяйки и
 * гостя однажды разъедется то, что дизайн просил держать одинаковым.
 */
export const CORNER_ICON_SIZE = 22;

/**
 * Ряд знаков в углу. Дети — сами знаки; их рисуют страницы, потому что состав
 * у хозяйки и гостя разный: у гостя шкатулки может не быть вовсе (тикет 119 —
 * закрытая витрина, ADR-0011).
 */
export function SceneCorner({ children }: { children: ReactNode }) {
  return <div className="imm-corner">{children}</div>;
}

/**
 * Один знак: ссылка-плашка 44×44 со знаком 22 внутри. Слово приходит пропом и
 * уходит в `aria-label` и `title` — на экране его нет.
 */
export function CornerMark({
  href,
  label,
  children,
}: {
  href: string;
  label: string;
  children: ReactNode;
}) {
  return (
    <Link href={href} aria-label={label} title={label} className="pressable imm-corner-mark">
      {children}
    </Link>
  );
}
