/**
 * Гасит ли пустота кадр ЕЩЁ и фильтром — или только вуалью.
 *
 * Темнота пустоты и темнота ночного КАДРА перемножаются, и это видно числом:
 * `gamer` при собственной светлоте 0.183 давал с ночным рецептом 0.095, а с
 * пустотой сверху — **0.040**, то есть почти чёрный экран (замер по кадрам,
 * 09.08).
 *
 * Правило, а не подобранное число: затемнение пустоты существует, чтобы
 * сказать «свет ещё не включали». В комнате, которая УЖЕ показана
 * невключённой, это сказано кадром, и второй раз гасить нечего. Вуаль
 * остаётся: она несёт ту же мысль, но не умножает яркость.
 *
 * УСЛОВИЕ СТАЛО ОДНИМ ВМЕСТО ДВУХ (тикет 133). Было `tod !== "night" &&
 * native !== "night"`: первая половина стерегла ВЫБРАННУЮ ночь, а её больше не
 * существует — положение упразднено, и в тип оно не входит. Осталась вторая:
 * четыре базы из десяти сняты ночью, и их кадр тёмен сам по себе, в любом
 * положении ручки.
 *
 * ВЕЧЕР СЮДА НЕ ПОПАЛ, и это осознанно. Вечер — не «свет не включали», а
 * мягкое `brightness(.84)` у дневной базы и `1.24` (то есть СВЕТЛЕЕ родного) у
 * ночной. Комната в вечернем положении показана освещённой, и пустота имеет
 * право сказать про себя своим слоем: .84 × .42 = 0.353 против 0.42 у дня —
 * разница в 16%, а не тот провал, который чинил тикет 107 (.6 × .42 = 0.252 на
 * дневной базе и 0.040 на ночной).
 *
 * ПРАВИЛО ОБЩЕЕ ДЛЯ ОБОИХ СЛОЁВ пустоты. Дизайн записал его рядом с
 * затемнением пустой ЗОНЫ (`emptyZoneSceneClarify.when`) — с той же мыслью и с
 * теми же последствиями.
 */
function emptyDarkensFilter(native: NativeTimeOfDay): boolean {
  return native !== "night";
}

/**
 * Фильтр кадра с учётом пустоты: темнота копится поверх грейдинга.
 *
 * ДВЕ ПУСТОТЫ НЕ СКЛАДЫВАЮТСЯ. В пустой комнате пусты и все её зоны, и наезд
 * давал бы .42 × .56 = 0.235 от исходного — 0.075 средней светлоты по десяти
 * комнатам, то есть тот же чёрный экран, который чинил тикет 107. Довод тот же,
 * что у ночного кадра: комната, уже показанная невключённой, второй раз не
 * гаснет. Поэтому фильтр пустой зоны берётся только там, где комнатного нет
 * (решение наше — дизайн назвал только ночь; вопрос ему выписан).
 *
 * ЗАТЕМНЕНИЙ В ПРОДУКТЕ ТРИ, И В ОДНОЙ СТРОКЕ ИХ НИКОГДА НЕ БОЛЬШЕ ДВУХ: вечер
 * (грейдинг) плюс РОВНО ОДНА пустота — комнаты или зоны. Ночного четвёртого
 * больше нет вовсе (тикет 133).
 *
 * ВУАЛИ РАЗВЕДЕНЫ ТАК ЖЕ. Вуаль пустой ЗОНЫ — отдельный слой сцены
 * (`SceneStage` → `.zoneDim`), и правило у него то же самое: на ночном кадре
 * остаётся (несёт мысль, не трогая яркость), в пустой КОМНАТЕ его нет вовсе —
 * две вуали `multiply` перемножаются ровно как две яркости.
 */
export function sceneFilter(
  tod: TimeOfDay,
  color: LightColor,
  empty: boolean,
  native: NativeTimeOfDay,
  emptyZone = false,
): string {
  const graded = gradingFilter(tod, color, native);
  let dim: string | null = null;
  if (emptyDarkensFilter(native)) {
    if (empty) dim = EMPTY_ROOM_FILTER;
    else if (emptyZone) dim = EMPTY_ZONE_FILTER;
  }
  if (!dim) return graded;
  return graded === "none" ? dim : `${graded} ${dim}`;
}

/** Слои сцены: грейдинг плюс вуаль пустой комнаты последней (она поверх всего). */
export function sceneLayers(
  tod: TimeOfDay,
  color: LightColor,
  empty: boolean,
  native: NativeTimeOfDay,
): GradeLayer[] {
  const layers = gradingLayers(tod, color, native);
  return empty ? [...layers, EMPTY_ROOM_VEIL] : layers;
}

/** Тон свечения метки зоны: тёплый берёт акцент комнаты, остальные — свой. */
export function bloomTint(color: LightColor, accent: string): string {
  if (color === "white") return "#EDEAE4";
  if (color === "candle") return "#E8A96B";
  return accent;
}
