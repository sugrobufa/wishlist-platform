/**
 * ПОЛОЖЕНИЯ РУЧКИ — то, что человек выбирает в настройках. Их три.
 *
 * «НОЧИ» СРЕДИ НИХ БОЛЬШЕ НЕТ (тикет 133, приёмка владельца 09.08.2026:
 * «с ночным вариантом мы всё-таки сильно перебрали, почти ничего не видно…
 * вечерний и ночной вариант должен быть один и тот же»). Дизайн согласился
 * убрать положение целиком (раунд 32, `round32-task34.json →
 * removeNightPosition`): «довода за отдельную ночь у меня нет: „праздник
 * вечером" покрывается вечером, а будущему экрану свет добавляется слоем, а
 * не положением — вернуть положение всегда дешевле, чем держать пустое».
 *
 * ПОЧЕМУ НЕ ОСТАВИЛИ ДВА ОДИНАКОВЫХ ПОЛОЖЕНИЯ: это ложь интерфейсу. Человек
 * выбрал бы «ночь», увидел вечер и решил, что сломалось.
 */
export const TIMES_OF_DAY = ["morning", "day", "dusk"] as const;

/**
 * Времена суток, в которые сняты САМИ БАЗЫ, — свойство фотографии, а не выбор.
 * Ночь здесь ОСТАЁТСЯ и остаться обязана: четыре базы из десяти сняты ночью
 * (`config/design.ts → Room.tod`), и от их родного времени считается вся
 * матрица переходов. Упразднено положение ручки, а не ночь как факт.
 */
export const NATIVE_TIMES_OF_DAY = ["morning", "day", "dusk", "night"] as const;
export const LIGHT_COLORS = ["warm", "white", "candle"] as const;

export type TimeOfDay = (typeof TIMES_OF_DAY)[number];
export type NativeTimeOfDay = (typeof NATIVE_TIMES_OF_DAY)[number];
export type LightColor = (typeof LIGHT_COLORS)[number];

/** Родное положение: кадр «как снято». Слоёв нет, identity. */
export const NATIVE_TIME_OF_DAY: TimeOfDay = "day";
export const NATIVE_LIGHT_COLOR: LightColor = "warm";

/**
 * Упразднённое положение — строка, которая ещё лежит в БД у комнат, заведённых
 * до тикета 133. Миграция `20260810_night_is_dusk` переписала их в `dusk`;
 * константа остаётся ради чтения, а не записи.
 */
export const RETIRED_TIME_OF_DAY = "night";

/**
 * Строка из БД → положение; мусор читается как родное, а не падает.
 *
 * ЗДЕСЬ ЖЕ — ЕДИНСТВЕННОЕ МЕСТО ПРАВИЛА «night → dusk» (условие тикета 133:
 * «ставить ОДНИМ местом, а не копировать значения в три ветки»). Миграция уже
 * прошла по базе, но правило нужно и после неё: старый кэш, чужой дамп,
 * ручная правка строки — и комната иначе прыгнула бы в «день», то есть в
 * ЧУЖОЕ время суток вместо соседнего. Дальше по коду ночи как выбора не
 * существует вовсе — её нет в типе.
 */
export function asTimeOfDay(value: unknown): TimeOfDay {
  if (TIMES_OF_DAY.includes(value as TimeOfDay)) return value as TimeOfDay;
  if (value === RETIRED_TIME_OF_DAY) return "dusk";
  return NATIVE_TIME_OF_DAY;
}

export function asLightColor(value: unknown): LightColor {
  return LIGHT_COLORS.includes(value as LightColor) ? (value as LightColor) : NATIVE_LIGHT_COLOR;
}

/**
 * Один слой грейдинга: градиент и его бленд. Фильтр живёт отдельно.
 * Бленд типизирован строго — иначе рецепт с опечаткой доедет до разметки и
 * молча превратится в `normal`.
 */
export type BlendMode = "screen" | "multiply" | "soft-light";
export type GradeLayer = { overlay: string; blend: BlendMode };

type Recipe = { filter: string | null; layers: GradeLayer[] };
const IDENTITY: Recipe = { filter: null, layers: [] };

