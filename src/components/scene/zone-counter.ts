// Счётчик зоны: сколько в ней вещей и сколько из них ещё свободно.
//
// ДВЕ РАЗНЫЕ СТРОКИ ДЛЯ ДВУХ ЗРИТЕЛЕЙ, и это не косметика, а инвариант №1.
//
//   ХОЗЯЙКЕ — только «N вещей» (`ZoneGrid.zoneCounts`, у дизайна
//   `zoneCounterGuest.ownerVariant`: «{m} вещей»). Про занятость по зонам ей не
//   показывается НИЧЕГО: у неё один счётчик на всю комнату.
//
//   ГОСТЮ — «сколько из скольких свободно». Форма — слово в слово из пакета
//   (`design/package/handoff/messages-ru.json` → `zoneCounterGuest`): ОДНА
//   строка «N из M», а не два числа рядом, «гость сразу видит и остаток, и
//   объём — второе решает, стоит ли заходить в зону». Слово «занято» дизайн
//   запретил отдельно: «оно из мира парковок, а тут комната» — вместо него
//   «уже дарят», та же фраза, что помечает вещь в списке.
//
// ЗДЕСЬ ТОЛЬКО ВЫБОР СЛУЧАЯ, без чисел и без слов: пять случаев легко
// перепутать местами («1 из 4 свободна» против «все 4 уже дарят»), и
// перепутанными они выглядят правдоподобно. Поэтому выбор — чистая функция под
// тестом, а не пять тернарников в разметке двух компонентов.
//
// ОТКУДА БЕРЁТСЯ `free`, объяснено в dto/zone-summary.ts: НЕ из кэшируемой
// сводки. Хозяйка открывает свою же гостевую ссылку и получает тот же
// кэшированный HTML — «7 свободно» при восьми вещах сказало бы ей ровно то,
// что запрещает инвариант №1. Второе число считает экран, вычитая занятые
// вещи зоны из некэшируемого канала «занято» (тикет 08), а хозяйке тот же
// канал отвечает пустотой.

/** Ключ строки `Scene.*` и её подстановки. */
export type ZoneCounterLine = {
  key: "summaryFreeSingle" | "summaryFreeAll" | "summaryFreeLast" | "summaryFreeSome" | "summaryFreeNone";
  values: { n: number; m: number };
};

/**
 * Гостевая строка счётчика зоны.
 *
 * @param total сколько вещей в зоне (`ZoneSummaryDto.count` — кэшируемо и
 *   безопасно: это её собственные вещи, а не чьи-то брони).
 * @param free сколько из них не занято. Считается на экране; пока канал
 *   «занято» не ответил, равно `total` — то же, что уже сказал кэш.
 *
 * Пустая зона сюда не приходит: у неё своя строка `Scene.summaryEmpty`
 * («Пока пусто»), и дублировать её случаем `empty` пакет тоже не стал.
 */
export function zoneCounterLine(total: number, free: number): ZoneCounterLine {
  const m = Math.max(0, total);
  // Занятых больше, чем вещей, быть не может: канал «занято» отдаёт брони по
  // всей комнате, а не по зоне, и лишнее сюда просто не доедет. Зажим стоит
  // против арифметики, а не против злого умысла.
  const n = Math.min(Math.max(0, free), m);

  if (n === 0) return { key: "summaryFreeNone", values: { n, m } };
  // «Вещь одна и свободна» — отдельный случай пакета: «1 из 1 свободна»
  // звучало бы как отчёт, а не как речь.
  if (n === m) return m === 1 ? { key: "summaryFreeSingle", values: { n, m } } : { key: "summaryFreeAll", values: { n, m } };
  if (n === 1) return { key: "summaryFreeLast", values: { n, m } };
  return { key: "summaryFreeSome", values: { n, m } };
}
