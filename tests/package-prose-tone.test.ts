/** Правило, снятое с прозы, не ищется вовсе; остальные — по всему корпусу. */
const HELD = TONE_RULES.filter(([name]) => !LIFTED.some(([lifted]) => lifted === name));

type Hit = { readonly rule: string; readonly line: Prose };

const hits: readonly Hit[] = HELD.flatMap(([rule, pattern]) =>
  prose.filter(({ text }) => pattern.test(text)).map((line) => ({ rule, line })),
);

/** Как нарушение выглядит в отчёте: файл, место, правило, сама строка. */
const say = ({ rule, line }: Hit) => `${at(line)} — ${rule}: ${line.text.trim().slice(0, 120)}`;

const isKnown = ({ rule, line }: Hit) =>
  KNOWN.some(
    (entry) => entry.rule === rule && entry.file === line.file && entry.place === line.place,
  );

describe("проза пакета под памяткой тона", () => {
  it("корпус прочитан — сторож не проверяет пустоту", () => {
    // Первое, что ломается у сторожа над чужими файлами: файл переименовали,
    // читатель вернул ноль строк, тест зеленеет вечно.
    expect(prose.length).toBeGreaterThan(500);
    expect(new Set(prose.map(({ file }) => file)).size).toBeGreaterThan(15);
  });

  it("каждое правило памятки отнесено — держим в прозе или сняли с причиной", () => {
    const unclassified = TONE_RULES.map(([name]) => name).filter(
      (name) =>
        !LIFTED.some(([lifted]) => lifted === name) && !HELD.some(([held]) => held === name),
    );
    expect(unclassified).toEqual([]);
    // И обратно: снятое правило обязано существовать. Опечатка в имени тихо
    // вернула бы правило в строй или, наоборот, сняла бы не то.
    const phantom = LIFTED.map(([name]) => name).filter(
      (name) => !TONE_RULES.some(([rule]) => rule === name),
    );
    expect(phantom).toEqual([]);
  });

  for (const [rule] of HELD) {
    it(`${rule} — только там, где названо поимённо`, () => {
      const fresh = hits.filter((hit) => hit.rule === rule && !isKnown(hit));
      expect(fresh.map(say)).toEqual([]);
    });
  }
});

describe("список известных мест — не индульгенция, выданная вперёд", () => {
  it("каждая запись всё ещё стоит на своём месте", () => {
    // Запись, пережившая строку, разрешает то, чего нет, — и завтра разрешит
    // случайно совпавшую новую. Раунд в адресе значим: приедет следующий
    // пакет — записи про прежний устареют, и тест велит перечитать его прозу.
    const stale = KNOWN.filter(
      (entry) =>
        !hits.some(
          ({ rule, line }) =>
            rule === entry.rule && line.file === entry.file && line.place === entry.place,
        ),
    ).map((entry) => `${entry.file}:${entry.place} — ${entry.rule}`);
    expect(stale).toEqual([]);
  });

  it("у каждой записи есть причина, а не отметка «известно»", () => {
    expect(
      KNOWN.filter(({ why }) => why.trim().length < 40).map((e) => `${e.file}:${e.place}`),
    ).toEqual([]);
  });
});

describe("сторож ловит, а не молчит", () => {
  it("список известных мест не пуст — проза правда нарушает памятку", () => {
    // Ожидание тикета 240 дословно: «Ожидание — не пустой список». Пустой
    // означал бы не чистую прозу, а сломанного читателя.
    expect(hits.length).toBeGreaterThan(0);
    expect(KNOWN.length).toBe(hits.length);
  });

  it("правило краснеет на строке живого README, из-за которой всё и затевалось", () => {
    // Та самая строка: пакет 52 сам признал её неверной («слово запрещено моей
    // же tone.md»), а живой файл её всё ещё держит. Правило без подложки можно
    // ослабить молча — с подложкой нельзя.
    const [, zoneSet] = TONE_RULES.find(([name]) => name === "«набор зон»") as [string, RegExp];
    expect(zoneSet.test("В профиле настройка так и называется «набор зон».")).toBe(true);
    expect(zoneSet.test("Наборы отличаются комнатами, а комнаты — полками")).toBe(false);
  });

  it("живая речь мимо правил проходит — «набор» сам по себе не запрещён", () => {
    const [, zoneSet] = TONE_RULES.find(([name]) => name === "«набор зон»") as [string, RegExp];
    for (const alive of [
      "Стандартный набор полок и «переезд без потерь»",
      "Наборы отличаются полками",
      "у комнаты полный набор: 12 зон + деньги",
    ]) {
      expect(zoneSet.test(alive), `ложная тревога: ${alive}`).toBe(false);
    }
  });
});
