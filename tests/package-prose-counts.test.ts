import { describe, it, expect } from "vitest";
import { claimsOfLive, claimsOfRound, head, mismatches, say, type Claim } from "./package-counts";
import { newestRound } from "./package-prose";

// СТОРОЖ ВТОРОЙ: ЧИСЛА СОСТАВА В ПРОЗЕ ПАКЕТА (тикет 240).
//
// Предложил его тот же дизайн и тем же письмом: «числа рядом со словами
// „ключей", „строк", „зон", „комнат" — сверять со счётом по файлу». Повод —
// третий его промах счётом за четыре пакета; мы ловили эти числа руками
// четырежды, и каждый раз одинаково: открывали файл и считали.
//
// ЧТО СЧИТАЕТСЯ, А ЧТО НЕТ — в `package-counts.ts`. Коротко: сторож считает
// только то, что привязано к ИМЕНИ (файл, раздел словаря, маска ключей,
// названная величина карты), и молчит про всё остальное. «Пять экранов» машине
// не сосчитать, а сторож, ловящий лишнее, начинают обходить формулировкой.
//
// ЧТО ОН ГОВОРИТ, КОГДА ПАДАЕТ: файл, место, обещано N, посчитано M и ЧЕМ
// посчитано. Иначе его начнут пропускать глазами — а это ровно тот исход,
// от которого тикет и заведён.

/**
 * ЖИВОЙ КОРПУС — файлы верхнего уровня (ими пакет работает) плюс последний
 * приехавший раунд. Тот же корпус, что у сторожа тона: у пакета одна проза, и
 * читать её двумя разными способами значило бы завести два разных пакета.
 */
const LIVE = [
  "README.md",
  "START-HERE.md",
  "SUMMARY.md",
  "icons.json",
  "items.json",
  "messages-ru.json",
  "motion.json",
  "places.json",
  "rooms.json",
  "tokens.json",
  "zone-row.json",
  "zones.json",
];

/**
 * ЗАКРЕПЛЁННЫЙ РАУНД — тот, по которому заведены записи ниже; новейший читается
 * вдобавок. Разбор — шапка `ANCHORED_ROUND` в `package-prose-tone.test.ts`:
 * записи называют файл и место, а `rooms.json` и `onboarding-set.json`
 * приезжают не каждым пакетом, и на round53/54 все три записи стали указывать
 * в пустоту разом.
 */
const ANCHORED_ROUND = "round52";

const live: readonly Claim[] = [
  ...claimsOfLive(LIVE),
  ...claimsOfRound(ANCHORED_ROUND),
  ...(newestRound() === ANCHORED_ROUND ? [] : claimsOfRound(newestRound())),
];

/**
 * ОТКРЫТЫЕ РАСХОЖДЕНИЯ — поимённо, с причиной, как у списков словаря. Пустым
 * список быть не обязан; обязан быть ОБЪЯСНЁННЫМ. Третьего пути нет: либо
 * расхождение названо, либо ожидание тихо подгоняют под факт.
 *
 * ДВЕ ЗАПИСИ УШЛИ ОТСЮДА ТИКЕТОМ 234, и ушли правильным способом — не правкой
 * ожидания, а исчезновением расхождения: полка «Бар и табак» заведена в четырёх
 * мужских комнатах, и `rooms.json` наконец считает то, что `zonesNote` обещал
 * вперёд карты — 134 адреса и 14 полок в мужской комнате.
 *
 * Оставшиеся три записи про то же самое — но в ПРИЛОЖЕННОЙ КОПИИ пакета 52.
 * Её `rooms.json` держит прежние 130 адресов, и править чужой файл мы не
 * будем: сторож считает каждую копию по ней самой, и это его свойство, а не
 * промах. Уйдут они вместе со следующей копией карты.
 *
 * Четвёртая — наша собственная, и она старше: замер мест в покое дизайн внёс в
 * контракт с наших слов («стало 23»), а после переразметок тикетов 233 и 234 их
 * стало 21. Расхождение уже названо вслух в `tests/empty-places.test.ts`; здесь
 * оно стоит вторым замком и заодно доказывает, что сторож достаёт до чисел,
 * которые считаются правилом, а не пересчётом ключей.
 */
type Known = { readonly at: string; readonly why: string };

const KNOWN: readonly Known[] = [
  {
    at: `${ANCHORED_ROUND}/rooms.json:zonesNote — «134 адреса всего»: обещано 134, посчитано 130`,
    why: "тот же `zonesNote` в приложенной копии файла — расхождение приехало вместе с пакетом 52",
  },
  {
    at: `${ANCHORED_ROUND}/rooms.json:zonesNote — «14 в мужских»: обещано 14, посчитано 13`,
    why: "то же самое в приложенной копии файла: состав мужской комнаты обещан вперёд полки `bar`",
  },
  {
    at: `${ANCHORED_ROUND}/onboarding-set.json:whatItPicks.shelvesPerRoom — «14 в мужских»: обещано 14, посчитано 13`,
    why: "третье место того же обещания — контракт экрана выбора комнат повторяет состав из `zonesNote`",
  },
  {
    at: "places.json:rule.drawIfWholeMeasured — «было 30 мест в покое, стало 23»: обещано 23, посчитано 21",
    why: "НАШ замер, внесённый дизайном в контракт с наших же слов. Уехал на одно место после переразметки «Геймера» (тикет 233) и ещё на одно после того, как в «Кабинете» появилась барная тележка (тикет 234); строку контракта мы не переписываем — это его файл. Названо и в `tests/empty-places.test.ts`",
  },
];

describe("числа состава сверены со счётом по файлу", () => {
  it("сторож нашёл, что считать, — он не проверяет пустоту", () => {
    // Первое, что ломается у сторожа над чужими файлами: якорь перестал
    // совпадать, обещаний ноль, тест зеленеет вечно.
    expect(live.length).toBeGreaterThan(5);
  });

  it("совпавшие обещания есть — сторож не красный по построению", () => {
    // Если бы КАЖДОЕ найденное число расходилось, это значило бы, что считаем
    // мы не то, что обещано. Сошедшиеся числа — доказательство обратного.
    const agreed = live.filter(({ promised, counted }) => promised === counted);
    expect(agreed.length).toBeGreaterThan(0);
  });

  it("расходятся только названные поимённо", () => {
    const fresh = mismatches(live).filter(
      (claim) => !KNOWN.some((entry) => entry.at === head(claim)),
    );
    expect(fresh.map(say)).toEqual([]);
  });

  it("каждая запись списка всё ещё расходится", () => {
    // Запись, пережившая расхождение, разрешает то, чего нет. Приедет карта с
    // полкой `bar` — три записи обязаны уйти отсюда в тот же час.
    const stale = KNOWN.filter(
      (entry) => !mismatches(live).some((claim) => head(claim) === entry.at),
    ).map(({ at }) => at);
    expect(stale).toEqual([]);
  });

  it("у каждой записи есть причина, а не отметка «известно»", () => {
    expect(KNOWN.filter(({ why }) => why.trim().length < 40).map(({ at }) => at)).toEqual([]);
  });
});

/**
 * ПРОВЕРКА НА НЕПУСТОТУ — ГЛАВНАЯ. Сторож, написанный после того, как ошибки
 * найдены руками, обязан доказать, что нашёл бы их сам. Подкладываем ему СТАРЫЕ
 * пакеты — те самые, где мы считали глазами, — и требуем поимённо каждый из
 * четырёх случаев.
 *
 * Ослабить правило после этого молча нельзя: подложка покраснеет.
 */
const CAUGHT: ReadonlyArray<readonly [string, string, string]> = [
  [
    "round47",
    "38 ключей обещано, 5 доставлено (письмо 51)",
    "round47/README.md:129 — «`strings-delta.json` (38 ключей»: обещано 38, посчитано 5",
  ],
  [
    "round47",
    "27 ключей `Pool.*` обещаны прозой дельты, а в пакете их нет вовсе",
    "round47/strings-delta.json:pool — «27 ключей раздела Pool.*»: обещано 27, посчитано 0",
  ],
  [
    "round47",
    "6 ключей `FriendRow.*` — то же самое",
    "round47/strings-delta.json:friendRow — «6 ключей FriendRow.*»: обещано 6, посчитано 0",
  ],
  [
    "round50",
    "«шесть строк плоско» против семи (письмо 56)",
    "round50/README.md:74 — «`ZoneCounterGuest`: шесть строк»: обещано 6, посчитано 7",
  ],
  [
    "round50",
    "«четырнадцать строк плоско» против тринадцати",
    "round50/README.md:75 — «`PoolInline`: четырнадцать строк»: обещано 14, посчитано 13",
  ],
  [
    "round51",
    "«теперь 15 полок» против двадцати (письмо 57)",
    "round51/strings-delta.json:toCheckOnYourSide.Onboarding.setDescriptionALL — " +
      "«Все полки сразу — разберёшься по ходу» — теперь 15 полок»: обещано 15, посчитано 20",
  ],
];

describe("сторож ловит все четыре случая, пойманные когда-то руками", () => {
  for (const [round, what, expected] of CAUGHT) {
    it(`${round}: ${what}`, () => {
      expect(mismatches(claimsOfRound(round)).map(head)).toContain(expected);
    });
  }

  it("«стало 23» против 21 — четвёртый случай, он же живой", () => {
    // Единственный из четырёх, который лежит не в письме раунда, а в ЖИВОМ
    // контракте `places.json`, и считается не пересчётом ключей, а правилом
    // самого пакета. Поэтому он и стоит в списке открытых расхождений выше.
    expect(mismatches(live).map(head)).toContain(
      "places.json:rule.drawIfWholeMeasured — «было 30 мест в покое, стало 23»: обещано 23, посчитано 21",
    );
  });

  it("верное число сторож не трогает — иначе его выключат на второй неделе", () => {
    // Пакет 48 первым за шесть раундов сошёлся по числам («28 + 5 = 33»), и
    // сторож обязан это подтвердить, а не поднять шум. Пакет 51 так же прав про
    // раздел `ZoneList`.
    const round48 = claimsOfRound("round48");
    expect(round48.map(head)).toContain(
      "round48/README.md:17 — «28 Pool.*»: обещано 28, посчитано 28",
    );
    expect(round48.map(head)).toContain(
      "round48/README.md:17 — «5 FriendRow.*»: обещано 5, посчитано 5",
    );
    expect(claimsOfRound("round51").map(head)).toContain(
      "round51/README.md:63 — «разделом `ZoneList` (7 живых строк»: обещано 7, посчитано 7",
    );
  });

  it("отчёт называет файл, строку и оба числа", () => {
    // Формат — требование тикета дословно: «файл, строка, обещано N, посчитано
    // M». Проверяем на настоящем расхождении, а не на выдуманной строке.
    const [first] = mismatches(claimsOfRound("round50"));
    expect(first).toBeDefined();
    const report = say(first as Claim);
    expect(report).toMatch(/^round50\/README\.md:\d+ — /u);
    expect(report).toContain("обещано 6, посчитано 7");
    expect(report).toContain("раздел `ZoneCounterGuest`");
  });
});
