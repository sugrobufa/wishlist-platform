//
// Зачем он есть. `design/package/handoff/README.md` двенадцать дней учил
// ОТМЕНЁННОЙ модели вещи v1 — «у вещи два состояния», «переход хочу → люблю»,
// «отправляет вещь в зал славы», — и нашёл это сам дизайн, пакетом 44, а не мы.
// Ущерба не случилось только потому, что `CLAUDE.md` держит модель v2 первым же
