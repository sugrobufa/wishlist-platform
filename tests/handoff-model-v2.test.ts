/**
 * ИСТОРИЧЕСКИЕ СТРОКИ — единственное исключение, и каждая названа целиком,
 * а не шаблоном. Шаблон («любая строка таблицы») со временем накрыл бы и живой
 * текст; строка целиком стареет честно — проверки ниже ловят и протухшую запись,
 * и запись, ничего не разрешающую.
 */
type Historical = {
  readonly file: (typeof GUARDED)[number];
  readonly line: string;
  readonly why: string;
};

