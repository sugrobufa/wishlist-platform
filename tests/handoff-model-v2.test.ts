type Line = { readonly file: string; readonly no: number; readonly text: string };

const readGuarded = (file: string) => readFileSync(join(HANDOFF, file), "utf8");

const lines: readonly Line[] = GUARDED.flatMap((file) =>
  readGuarded(file)
    .split(/\r?\n/u)
    .map((text, index) => ({ file, no: index + 1, text })),
);

/** Строка разрешена, только если названа в списке целиком и в своём файле. */
const isHistorical = (file: string, text: string) =>
  HISTORICAL.some((entry) => entry.file === file && entry.line === text.trim());

/** Проход по файлам ровно тот же, каким пользуются проверки правил. */
const hits = (rule: RegExp): string[] =>
  lines
    .filter(({ file, text }) => rule.test(text) && !isHistorical(file, text))
    .map(({ file, no, text }) => `${file}:${no} — ${text.trim()}`);

describe("читаемые файлы пакета не учат отменённой модели v1", () => {
  for (const { word, why, rule } of RETIRED) {
    it(`${word} — ни разу (${why})`, () => {
      expect(hits(rule)).toEqual([]);
    });
  }
});

describe("сторож проверен на себе — он ловит, а не проверяет пустоту", () => {
  for (const { word, rule, sample } of RETIRED) {
    it(`${word}: правило краснеет на строке, которой README жил двенадцать дней`, () => {
      expect(rule.test(sample)).toBe(true);
    });
  }

  it("подложка не проехала бы и ПРОХОДОМ ПО ФАЙЛУ, а не только регекспом", () => {
    // Между правилом и проходом стоит список исторических исключений, и
    // ошибиться легче всего именно там: запись, взятая слишком широко, тихо
    // разрешила бы половину файла. Проверяем весь путь целиком.
    for (const { word, sample } of RETIRED) {
      const caught =
        RETIRED.some(({ rule }) => rule.test(sample)) && !isHistorical("README.md", sample);
      expect(caught, `${word}: строка проехала бы мимо прохода по файлу`).toBe(true);
    }
  });

  it("живая речь мимо правил проходит — сторож не запрещает слово «состояние»", () => {
    // Обратная сторона той же честности: правило, ловящее лишнее, начинают
    // обходить формулировкой, и оно перестаёт значить что-либо.
    for (const alive of [
      "Экраны: телефонный главный и пустое состояние — турн 23 макета.",
      "| 14 | Переключатель пола, лента всех десяти комнат в пяти состояниях |",
      "Односторонняя подписка — законное состояние, а не незавершённая заявка.",
      "анимация прозрачности перебивает инлайновое состояние",
      "**Комната — чего хочется.** Вещь бронируется, у неё есть степень желания.",
    ]) {
      expect(
        RETIRED.filter(({ rule }) => rule.test(alive)).map(({ word }) => word),
        `ложная тревога на живой строке: ${alive}`,
      ).toEqual([]);
    }
  });
});

describe("список исторических строк — не индульгенция, выданная вперёд", () => {
  it("каждая запись всё ещё стоит в своём файле", () => {
    // Запись, пережившая строку, разрешает то, чего нет, — и завтра разрешит
    // случайно совпавшую новую.
    const stale = HISTORICAL.filter(
      ({ file, line }) =>
        !readGuarded(file)
          .split(/\r?\n/u)
          .some((text) => text.trim() === line),
    ).map(({ file, line }) => `${file}: ${line}`);
    expect(stale).toEqual([]);
  });

  it("каждая запись правда что-то разрешает", () => {
    // Строка, не нарушающая ни одного правила, в списке исключений лишняя:
    // она только приучает добавлять сюда что попало.
    const idle = HISTORICAL.filter(({ line }) => !RETIRED.some(({ rule }) => rule.test(line))).map(
      ({ file, line }) => `${file}: ${line}`,
    );
    expect(idle).toEqual([]);
  });
});

it("новый читаемый файл пакета не проедет мимо сторожа", () => {
  const present = readdirSync(HANDOFF)
    .filter((name) => name.endsWith(".md"))
    .sort();
  expect(
    present,
    "появился .md в handoff/ — решите, читаемый он (в GUARDED) или письмо раунда (в ROUND_LETTERS)",
  ).toEqual([...GUARDED, ...ROUND_LETTERS].sort());
});

describe("README учит модели v2, а не отмалчивается", () => {
  // Второй способ «пройти» сторож — вычистить раздел до пустоты. Тогда агент,
  // начавший с README, не соберёт v1, но и v2 не узнает: ровно та же дыра,
  // только тихая.
  const readme = readGuarded("README.md");

  it("«Главная идея» называет место, а не состояние", () => {
    // Формулировка НЕ закреплена дословно: файл пишет дизайн, и «Поля состояния
    // у вещи НЕТ» (пакет 45) говорит ровно то же, что наше «Состояний у вещи
    // НЕТ». Требуем смысл — отрицание состояния рядом с именем отменённой
    // модели, — а не совпадение букв: иначе сторож ронял бы каждый их пакет.
    // Формулировка НЕ закреплена дословно: файл пишет дизайн, и его «Поля
    // состояния у вещи НЕТ» (пакет 45) говорит ровно то же, что наше
    // «Состояний у вещи НЕТ». Требуем смысл — отрицание состояния, — а не
    // совпадение букв, иначе сторож ронял бы каждый их пакет на редактуре.
    expect(readme).toMatch(/состояни[а-я]*\s+у\s+вещи\s+НЕТ/iu);
    expect(readme).toContain("Комната — чего хочется");
    expect(readme).toContain("Сокровищница — что уже моё");
    // ИСТОЧНИК РЕШЕНИЯ НАЗВАН — но не обязательно НАШИМ номером. Файл пишет
    // дизайн, и нумерует он письмами: «отменена решением владельца 09.08.2026
    // (письмо 25)». Требовать здесь «тикет 124» значило бы требовать от чужого
    // проекта нашей нумерации — сторож ронял бы каждый их пакет на ровном
    // месте. Держим то, что действительно важно: дату решения и ссылку хоть на
    // одну сторону переписки.
    expect(readme).toContain("09.08.2026");
    expect(readme).toMatch(/тикет 124|письмо 25/u);
  });

  it("обратимость места и необратимость имени сказаны словами", () => {
    expect(readme).toContain("Вернуть в комнату");
  });

  it("карточка вещи названа своими турнами, а не турном 8", () => {
    // Не «слова нет в файле», а «оно не стоит УТВЕРЖДЕНИЕМ». Пакет 45 цитирует
    // прежнюю строку, чтобы объявить её замену, и это законно: запрещать
    // цитату в errata значило бы запрещать дизайну признавать свои ошибки.
    // Ловим форму — цитата обязана стоять после слов «Прежняя строка».
    for (const line of readme.split(/\r?\n/u)) {
      if (!/карточк[а-я]*\s+вещи\s+переиспользуют/iu.test(line)) continue;
      expect(line, `строка учит турном 8 без отрицания: ${line}`).toMatch(/Прежняя строка/u);
    }
    expect(readme).toContain("47a");
  });
});
