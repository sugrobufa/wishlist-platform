/**
 * Граница слова по-русски: `\b` в JS смотрит на латиницу и кириллицу не видит.
 * Без этого «вы» ловилось бы внутри «выбери», а «кадр» — внутри «кадра».
 */
const LETTER = "[А-Яа-яЁёA-Za-z]";
const asWord = (body: string) => new RegExp(`(?<!${LETTER})(?:${body})(?!${LETTER})`, "iu");

/**
 * РОД ЧЕЛОВЕКА (правило раунда 41, тикет 172) — три куска одного регекспа,
 * вынесенные наверх, потому что каждый требует объяснения.
 *
 * `SUBJECT` — кого строка называет ДЕЙСТВУЮЩИМ ЛИЦОМ: «ты» и подстановка
 * имени хозяйки. Имя после предлога подлежащим не бывает («У {name}
 * появилась полка» — появилась ПОЛКА), поэтому предлог его снимает: иначе
 * правило ловило бы `Feed.shelfOpened`, где род неизбежен и относится к вещи.
 *
 * `GENDERED` — формы, у которых род виден: прошедшее время (-л, -ла, -лся,
 * -лась) и краткие прилагательные, которые говорят О ЧЕЛОВЕКЕ. Ни «один/
 * одна», ни «сам/сама», ни «занят/занята» сюда не входят нарочно: они чаще
 * стоят при вещи («бронь снялась сама», «ровно один раз»), и их род тоже
 * неизбежен.
 *
 * `GAP` — до двух слов между подлежащим и формой: «ты ничего не должен»
 * ловится, а два соседних предложения — уже нет.
 */
const PREPOSITION = "у|от|для|к|ко|с|со|о|об|в|во|при|про|за|над|под|без|до|после|из|на|по|через";
const SUBJECT = `ты|(?<!(?:${PREPOSITION})\\s)\\{name\\}`;
const GENDERED =
  "[а-яё]{3,}(?:лась|лся|ла|л)" +
  "|должен|должна|обязан|обязана|готов|готова|уверен|уверена|рад|рада|согласен|согласна";
const GAP = "(?:\\s+[^\\s]+){0,2}[\\s,—:-]+";

/**
 * Само правило рода отдельным именем: с раунда 42 оно проверяет не только
 * словарь, но и КОНТРАКТ, и присланные вёрстки, и собранное письмо целиком
 * (описание — у `describe` ниже), а один и тот же предикат в четырёх местах
 * обязан быть одним и тем же объектом, а не четырьмя копиями регекспа.
 */
const GENDER_RULE = asWord(`(?:${SUBJECT})${GAP}(?:${GENDERED})|(?:${GENDERED})\\s+\\{name\\}`);

/**
 * Правила памятки, которые машина умеет проверить.
 *
 * Чего в списке НЕТ и почему:
 * - «товар» — в памятке он в столбце «не говорим», но пакет сам пишет
 *   «Не похоже на страницу товара» про страницу магазина. Пакет — источник
 *   правды, значит слово живое;
 * - «пространство» — тоже из столбца «не говорим», но турн 13a принятой
 *   доски сам пишет «Тихое пространство» (знак продукта над входом) и
 *   «Обставь пространство тем, что любишь» (манифест). Тот же прецедент,
 *   что у «товара»: доска — источник правды, слово живое (тикет 56);
 * - «повод», «статус», «тип», «флаг» — пакет говорит «дождутся следующего
 *   повода», а остальные слишком общие: тест ловил бы обычную речь.
 */
const TONE_RULES: ReadonlyArray<readonly [string, RegExp]> = [
  // «Ни одного во всём продукте. Радость передаётся смыслом, а не пунктуацией.»
  ["восклицательный знак", /!/u],
  // «Подарил(а) {name}» → «Подарок от {name}». Скобка выдаёт базу данных.
  ["родовая скобка", /\([А-Яа-яЁё/]{1,4}\)/u],
  // Скобка — половина беды; вторая половина — род БЕЗ скобки. «Ты обещал»,
  // «Мила убрала», «ты ничего не должен», «какой ты выбрала»: имя хозяйки
  // может быть мужским, а имени гостя мы не знаем вовсе (правило дизайна,
  // round41/tone.md — «подставь мужское имя и мужского гостя: если фраза
  // сломалась, её надо переписать»). Лечение всегда одно — назывной оборот.
  //
  // Правило поймало нас самих ровно дважды: `Settings.lightHint` («какой ты
  // выбрала») и `StarterPack.caption` («который ты выбрала»). Обе строки
  // переписаны тикетом 172; вторая тогда уехала от доски, откуда была взята
  // дословно, а раундом 42 дизайн прислал ровно нашу редакцию — расхождения
  // больше нет (запись об этом — в списке сирот ниже).
  ["род человека", GENDER_RULE],
  // «Слово „ошибка“ в текстах не встречается ни разу.»
  ["слово «ошибка»", asWord("ошибк[а-я]*")],
  // Везде «ты»: комната — своё пространство, а не учреждение.
  ["обращение на «вы»", asWord("вы|вас|вам|вами|ваш[а-я]*")],
  // Слова технического контракта в интерфейсе не существуют.
  ["слово из технического контракта", asWord("наезд[а-я]*|кадр[а-я]*|хотспот[а-я]*|пресет[а-я]*")],
  // «Набор зон» — слово контракта, и ловится ПАРОЙ, а не одним словом.
  //
  // ПРАВИЛО СУЖЕНО (раунд 29). Оно ловило «набор[а-я]*» целиком — «от набора
  // зависят зоны комнаты» это та же мысль теми же словами, — но сам пакет
  // теперь говорит «Наборы отличаются полками» в `Onboarding.zoneSetHint`.
  // Тот же прецедент, что у «товара» и «пространства» выше: доска и пакет —
  // источник правды, и слово живое. Запрет остаётся на связке, которой пакет
  // не пользуется ни разу; на месте одиночного слова в наших собственных
  // строках по-прежнему живёт «заготовка».
  ["«набор зон»", asWord("набор[а-я]*\\s+зон[а-я]*")],
  // Столбец «не говорим» из памятки — то, что нельзя спутать с живой речью.
  [
    "слово не из словаря продукта",
    asWord(
      "вишлист[а-я]*|айтем[а-я]*|забук[а-я]*|зарезервир[а-я]*|окказ[а-я]*|ивент[а-я]*|" +
        "профил[ья][а-я]*|категори[а-я]*|секци[а-я]*|позици[а-я]*|" +
        "коллекци[а-я]*|архив[а-я]*|упс",
    ),
  ],
];

/**
 * ПАДЕЖНАЯ ЛОВУШКА ТОКЕНА — вторая ловушка ровно того же устройства, что род
 * (раунд 42, письмо 45; `round41/letters.json` → `templates.itemGone`,
 * памятка `design/round42/tone.md` → «Падеж — вторая ловушка токена»).
 *
 * Разбор дизайна: «больше нет» требует РОДИТЕЛЬНОГО падежа («шёлкового
 * шарфа»), а `{item}` приезжает в ИМЕНИТЕЛЬНОМ — фраза ломается на первом же
 * подставленном значении: «„Шёлковый шарф" больше нет в комнате». Лечение то
 * же, что у рода: назывной оборот, падежа не требующий («больше НЕ В
 * комнате»), — он держит любое значение.
 *
 * ЛОВИТСЯ НЕ СЛОВО, А СОСЕДСТВО, И В ОБЕ СТОРОНЫ. Падеж требуется и когда
 * токен стоит после оборота («больше нет {item}»), и когда перед ним
 * («„{item}" больше нет»): это одно и то же управление. Наши обе строки были
 * ВТОРЫМ случаем — правило, написанное только на первый, проверяло бы пустоту.
 *
 * СПИСОК ОБОРОТОВ — НЕ ГРАММАТИКА, А ПЕРЕЧЕНЬ ИЗВЕСТНЫХ ЛОВУШЕК, и он обязан
 * расти: начат с тех, что уже поймали. Токены — только те, на месте которых
 * встаёт СУЩЕСТВИТЕЛЬНОЕ человека; `{count}`, `{date}`, `{percent}`, `{free}`
 * в падежные обороты не попадают — там число или дата.
 */
const CASE_TOKEN = "«?\\{(?:item|name|giver|zone|label)\\}»?";
/** До двух слов между оборотом и токеном — дальше это уже другая клауза. */
const CASE_NEAR = "(?:\\s+[^\\s.;:!?]+){0,2}\\s+";
const CASE_TRAPS: ReadonlyArray<readonly [string, string]> = [
  ["«больше нет» — родительный", "больше\\s+нет"],
  ["«нет …» — родительный", "нет"],
  ["«не стало» — родительный", "не\\s+стало"],
  ["«лишился» — родительный", "лишил(?:ся|ась|ись)"],
];

/** Оборот и токен в одной клаузе, в любом порядке. */
const caseTrap = (turn: string): RegExp => {
  const phrase = `(?<!${LETTER})(?:${turn})(?!${LETTER})`;
  return new RegExp(
    `(?:${CASE_TOKEN})${CASE_NEAR}${phrase}|${phrase}${CASE_NEAR}(?:${CASE_TOKEN})`,
    "iu",
  );
};

/**
 * ПОЛЯ ПИСЬМА ПОИМЁННО. Вывод раунда 42 стоит того, чтобы стать кодом:
 * **«проверять надо прочитанное, а не написанное»**. Прехедеры двух вёрсток
 * прошли мимо правила рода не потому, что правило было слабым, а потому что
 * прехедер не считали текстом: в вёрстке он спрятан в невидимом `<span>`, а
 * человек читает его в списке входящих второй строкой после темы.
 *
 * Отсюда карта: КАЖДЫЙ ключ словаря писем обязан попасть в какое-то поле, и
 * каждое поле проходит правило рода. Появится новый ключ — тест назовёт его
 * неотнесённым, и мимо правила он не проедет.
 */
const MAIL_FIELDS: ReadonlyArray<readonly [string, RegExp]> = [
  ["тема", /^subject(?:NoName)?$/u],
  // `taken` — та же строка прехедера, оставшаяся с тикета 160; сборкой письма
  // она не читается, но лежит в словаре и правило проходит наравне с прочими.
  ["прехедер", /^(?:preheader(?:NoItem)?|taken)$/u],
  ["надстрочная", /^overline$/u],
  ["заголовок", /^(?:title|titleNoName|titleTail|when[A-Za-z0-9]+)$/u],
  [
    "тело и тихая строка",
    /^(?:body|bodyNoItem|quiet|quietNoName|hint|tail|tailLead|tailAction|tailTrail|tailTrailNoName)$/u,
  ],
  ["плашка вещи", /^(?:item|zone|room|free|freeNoName|things(?:One|Few|Many)|occasion)$/u],
  ["кнопка и дорога", /^(?:cta|link|bookings|bookingsHint)$/u],
  ["подвал", /^(?:footer|signature)$/u],
];

/** Кнопка, подпись, заголовок — без точки. Длиннее — уже фраза, ей точка можно. */
const SHORT_LINE = 40;

function violations(check: (value: string) => boolean, dictionary: Map<string, string>): string[] {
  return [...dictionary]
    .filter(([, value]) => check(value))
    .map(([key, value]) => `${key} = ${JSON.stringify(value)}`);
}

describe("тон русского словаря", () => {
  for (const [name, pattern] of TONE_RULES) {
    it(`${name} — ни разу`, () => {
      expect(violations((value) => pattern.test(value), ru)).toEqual([]);
    });
  }

  it("короткая строка не заканчивается точкой", () => {
    const dotted = violations(
      (value) => value.length <= SHORT_LINE && value.trimEnd().endsWith("."),
      ru,
    );
    expect(dotted).toEqual([]);
  });

  it("пустых значений нет", () => {
    expect(violations((value) => value.trim() === "", ru)).toEqual([]);
  });

  it("восклицательных знаков нет и в английском каркасе", () => {
    // Памятка: «ни одного во всём продукте». Английский переведут позже, но
    // тон переносится, а не изобретается заново.
    expect(violations((value) => value.includes("!"), en)).toEqual([]);
  });
});

