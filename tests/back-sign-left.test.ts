// ЗНАК «НАЗАД» СТОИТ СЛЕВА (тикет 254, приёмка владельца 16.08.2026).
//
// ЖАЛОБА дословно: «в нескольких страницах вижу стрелку вернуться в правом
// углу, хотя у нас везде стандарт в левом». «Несколько страниц» — это два вида
// одного экрана: `/room/add` («← В комнату») и `/room/add?hall=1`
// («← В сокровищницу»). Обход всех «←» в разметке даёт девять мест, и справа
// стояло ровно одно.
//
// ПРИЧИНА БЫЛА ИСТОРИЧЕСКОЙ, А НЕ СЛУЧАЙНОЙ, и потому опасной: знаков в шапке
// когда-то было ДВА — «Назад» внутри карточки и выход из неё, — и
// `margin-left: auto` честно разводил их по краям. Шаг «что это для тебя» снят
// тикетом 124, знак остался один, а правило осталось вместе с ним и унесло
// единственный знак вправо. Такое не ловится глазами на ревью: строка выглядит
// осмысленной ровно до того момента, когда узнаёшь, что второго знака больше
// нет.
//
// ПОЧЕМУ СТОРОЖ ЧИТАЕТ CSS, А НЕ МЕРЯЕТ ЭКРАН. Отступ, унёсший знак, — одна
// строка в модуле, и вернуться она может только туда же. Рендерить экран
// добавления ради неё значило бы поднимать половину продукта (форма, зоны,
// пресайн загрузки), а живую геометрию и без того меряет телефонный e2e.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const read = (relative: string) =>
  readFileSync(fileURLToPath(new URL(relative, import.meta.url)), "utf8");

const css = read("../src/app/room/add/add-item.module.css");
const flow = read("../src/app/room/add/add-item-flow.tsx");

/** Любой способ прижать элемент к правому краю авто-отступом. */
const PUSH_RIGHT = /margin(?:-inline)?-(?:left|start)\s*:\s*auto/u;

describe("254 — знак «назад» на экране добавления вещи стоит слева", () => {
  it("авто-отступа в модуле нет вовсе — ни в одном правиле", () => {
    // Проверяется ФАЙЛ ЦЕЛИКОМ, а не только `.navExit`: разводить в этой шапке
    // больше нечего, и любое новое `margin-left: auto` здесь означает, что знак
    // снова уехал — неважно, под каким классом.
    const guilty = css
      .split(/\r?\n/u)
      .map((line, at) => [at + 1, line] as const)
      .filter(([, line]) => PUSH_RIGHT.test(line) && !/^\s*(?:\/\*|\*)/u.test(line));
    expect(
      guilty.map(([at, line]) => `add-item.module.css:${at} — ${line.trim()}`),
      "в модуле карточки добавления снова есть авто-отступ: знак «назад» уедет вправо",
    ).toEqual([]);
  });

  it("класс `.navExit` остался жив ради своего цвета, а не удалён заодно", () => {
    // Он тише обычного `.navLink` (`--color-text-faint` против
    // `--color-text-muted`), и это разница смысловая: выход из карточки —
    // самое тихое, что есть в шапке.
    const at = css.indexOf("\n.navExit {");
    expect(at, "правила .navExit в модуле нет").toBeGreaterThan(-1);
    const body = css.slice(at, css.indexOf("}", at));
    expect(body).toMatch(/color:\s*var\(--color-text-faint\);/u);
  });

  it("знак — первый и единственный узел шапки, а не второй справа", () => {
    // Стандарт восьми остальных экранов: знак открывает страницу. Ловим место в
    // потоке, а не пиксели, — правая позиция всегда начиналась с того, что знак
    // оказывался не первым.
    const open = flow.indexOf("<nav className={s.nav}>");
    expect(open, "шапки с путём назад в форме добавления нет").toBeGreaterThan(-1);
    const inner = flow.slice(flow.indexOf(">", open) + 1, flow.indexOf("</nav>", open));
    expect(
      /<([A-Za-z][\w.]*)/u.exec(inner)?.[1],
      "первым узлом шапки стоит не знак «назад»",
    ).toBe("Link");
    expect(
      [...inner.matchAll(/<Link\b/gu)],
      "в шапке снова два знака — тогда и авто-отступ вернётся",
    ).toHaveLength(1);
    // Тот же отступ классом утилиты — обход сторожа, а не другое решение.
    expect(inner, "знак прижат вправо утилитой Tailwind").not.toMatch(/\bml-auto\b/u);
  });
});
