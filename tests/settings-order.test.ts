// ПОРЯДОК РАЗДЕЛОВ НАСТРОЕК — решение владельца, а не случайность (тикет 180,
// постановка 11.08.2026):
//
// > «Задать наименование комнаты надо убрать ниже выбора комнат»
// > «То, что чаще всего будет использоваться — выбор комнаты и время суток и
// > свет — надо поднять повыше»
//
// До этого «Интерьер» и «Свет» стояли третьим и четвёртым, а техническая
// строка адреса — второй: короткое имя задают один раз и почти никогда не
// меняют, это настройка ссылки, а не комнаты.
//
// ЗАЧЕМ ТЕСТ. Порядок разделов теперь несёт решение, и потерять его проще
// всего нечаянно: раздел переезжает вместе с любой правкой соседнего JSX, и в
// приёмке это читается как «вы вернули как было». Проверка обязана падать при
// следующем переезде — тогда переезд станет решением, а не опечаткой.
//
// Порядок читается из ИСХОДНИКА страницы: экран серверный, ходит в БД за
// профилем, комнатой и счётчиками зон, и рендерить его в юните значило бы
// поднимать всё это ради проверки последовательности девяти строк.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const read = (relative: string) =>
  readFileSync(fileURLToPath(new URL(relative, import.meta.url)), "utf8");

const page = read("../src/app/settings/page.tsx");

/**
 * Девять разделов экрана в том порядке, в каком их видит человек. Слева
 * направо сверху вниз: сначала две частые ручки, потом всё остальное.
 */
const EXPECTED_ORDER = [
  "PresetSection", // Интерьер
  "LightSection", // Свет и время суток
  "ProfileSection", // О себе
  "NickSection", // Адрес комнаты
  "ZonesSection", // Полки
  "BirthdaySection", // День рождения (тикет 187 — был «Праздник»)
  "HallSection", // Сокровищница
  "AccessSection", // Вход и доступ
  "DataSection", // Данные
] as const;

/** Имена секций в порядке их появления в разметке (импорты не считаются). */
function sectionsOf(source: string): string[] {
  const known = new Set<string>(EXPECTED_ORDER);
  return [...source.matchAll(/<([A-Z][A-Za-z]*)/gu)]
    .map((match) => match[1] as string)
    .filter((name) => known.has(name));
}

describe("порядок разделов настроек (тикет 180)", () => {
  it("частое наверху, техническое внизу — ровно тот порядок, что назвал владелец", () => {
    expect(sectionsOf(page)).toEqual([...EXPECTED_ORDER]);
  });

  it("каждый раздел ровно один раз — переезд не превращается в копию", () => {
    const seen = sectionsOf(page);
    expect(new Set(seen).size).toBe(seen.length);
  });

  it("«Адрес комнаты» стоит НИЖЕ выбора комнаты — это половина постановки", () => {
    const seen = sectionsOf(page);
    expect(seen.indexOf("NickSection")).toBeGreaterThan(seen.indexOf("PresetSection"));
  });

  it("условные разделы остались условными — переезд их не раскрыл", () => {
    // Граница тикета: `LightSection` рисуется только при знакомом пресете
    // (иначе грейдинг считать не от чего), `AccessSection` — только когда
    // сервис входа ответил. Переезд не имеет права сделать их безусловными.
    expect(page).toMatch(/\{preset && \(\s*<LightSection/u);
    expect(page).toMatch(/\{harden !== null && \(\s*<AccessSection/u);
  });
});
