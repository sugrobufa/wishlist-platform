import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * ПУСТАЯ ЗОНА: ОДНО МЕСТО, И ОНО НАЖИМАЕТСЯ (тикет 193).
 *
 * Приёмка владельца 11.08.2026: «отрисовываются 3 пустых иконки, причём
 * рисуются все 3 по-разному… смысл пустых плиток не очевиден».
 *
 * Мест было три, различались они ТОЛЬКО прозрачностью (.45 / .28 / .16,
 * затухание в глубину с доски Б27), и все три были немыми — `aria-hidden`, ни
 * ссылки, ни обработчика. При этом строкой выше стояла живая кнопка
 * «+ Добавить вещь»: «сюда поставят» говорили прямоугольники, которые нельзя
 * нажать, а поставить умел сосед.
 *
 * Тест читает исходники, а не разметку в браузере, по той же причине, что и
 * соседи по раскладке: панель браузера кадры не композитит, а состояние
 * «зона пуста» в живой комнате стенда не достаётся без записи в базу.
 */
describe("пустая зона", () => {
  const emptyZone = readFileSync(
    join(process.cwd(), "src/components/zone/empty-zone.tsx"),
    "utf8",
  );
  const roomPage = readFileSync(join(process.cwd(), "src/app/room/page.tsx"), "utf8");

  it("место одно — тройки прозрачностей больше нет", () => {
    // Именно связка трёх значений и кодировала глубину. Вернётся она —
    // вернутся и три прямоугольника.
    expect(emptyZone).not.toMatch(/\["73",\s*"47",\s*"29"\]/u);
    expect(emptyZone).toMatch(/const SLOT_ALPHA = "73"/u);
    // И ни одного `map` по местам: три места рисовались перебором.
    expect(emptyZone).not.toMatch(/SLOT_ALPHA\.map/u);
  });

  it("в панели сцены место — ссылка в форму добавления этой же зоны", () => {
    expect(emptyZone).toMatch(/href=\{`\/room\/add\?zone=\$\{zoneKey\}`\}/u);
    // Ссылкой, а не обработчиком: долгое нажатие и «открыть в новой вкладке»
    // обязаны работать — то же правило, что у плитки вещи (тикет 186).
    expect(emptyZone).not.toMatch(/onClick=\{\(\) => [^}]*\/room\/add/u);
  });

  it("у нажимаемого места есть имя, у немого — нет", () => {
    // `aria-label` берётся из словаря, а не сочиняется в разметке.
    expect(emptyZone).toMatch(/aria-label=\{t\("cta"\)\}/u);
    // Немое место на полном экране зоны по-прежнему скрыто от читалки: там
    // ниже стоит настоящая кнопка, и второе имя было бы эхом.
    expect(emptyZone).toMatch(/aria-hidden\s*\n?\s*className="relative h-26/u);
  });

  it("место 96×96 — цель нажатия заведомо выше пола 44", () => {
    // Числа переехали в CSS вместе с приездом пакета 46: 96×96 — это не
    // «побольше на всякий случай», а размер, при котором место читается как
    // площадка для вещи, а не как кнопка со знаком.
    const css = readFileSync(
      join(process.cwd(), "src/components/zone/empty-zone.module.css"),
      "utf8",
    );
    expect(css).toMatch(/\.slot\s*\{[^}]*width:\s*96px/u);
    expect(css).toMatch(/\.slot\s*\{[^}]*height:\s*96px/u);
    // Прежних ступеней прозрачности в ПРАВИЛАХ нет ни одной: дизайн померил
    // их контрастом к базе комнаты — 2.3 : 1 и 1.5 : 1 при нашем же поле .48,
    // то есть две из трёх были ниже пола (пакет 46). Комментарии из проверки
    // вырезаны нарочно: они эти же числа объясняют, и запрещать их там
    // значило бы запрещать причину рядом с решением.
    const rules = css.replace(/\/\*[\s\S]*?\*\//gu, "");
    expect(rules).not.toMatch(/0?\.28|0?\.16/u);
  });

  it("hover за воротами, как велит конвенция", () => {
    const css = readFileSync(
      join(process.cwd(), "src/components/zone/empty-zone.module.css"),
      "utf8",
    );
    expect(css).toMatch(/@media \(hover: hover\) and \(pointer: fine\)/u);
  });

  it("в пустой зоне пилюля «+ Добавить вещь» не рисуется", () => {
    // Дубль того же действия в двух сантиметрах — ровно то замечание, из-за
    // которого заведён тикет. «Показать все» при этом остаётся.
    expect(roomPage).toMatch(/\{items\.length > 0 && \(\s*<Link\s+href=\{`\/room\/add\?zone=/u);
    expect(roomPage).toMatch(/tZone\("openFull"\)/u);
  });
});
