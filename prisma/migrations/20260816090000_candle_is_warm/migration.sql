--
-- ПОЧЕМУ. Владелец: «Свечной свет и Тёплый непонятно чем отличается, я не
-- заметил на комнате. Если разницы нет, то оставь только один из них —
-- Тёплый». Разница у положений была: «свечной» это `saturate(1.06)` плюс слой
-- `rgba(232,168,106,.18)` на `soft-light`, то есть янтарная плёнка в 18%
-- поверх фотографии, которая и без того снята тёплой. Числом разница есть,
-- глазами её нет — тот же урок, которым кончилась ночь (тикет 112: средняя
-- светлота выросла 0.238 → 0.268, а на телефоне не изменилось ничего): свет
-- принимается на телефоне, а не числом.
--
-- ДВА ОДИНАКОВЫХ ПОЛОЖЕНИЯ В НАСТРОЙКАХ — ЛОЖЬ ИНТЕРФЕЙСУ: человек выбирает
-- «свечной», видит тёплый и решает, что сломалось. Поэтому положение убрано
-- целиком, а не приравнено к тёплому. Приём и довод дословно те же, что у
-- миграции `20260810090000_night_is_dusk`.
--
-- РИСКА НЕТ. Поле строковое, значений было три; ни ключей, ни ограничений на
-- него не заведено, вычислять по нему нечего. Единственное, что меняется у
-- существующей комнаты, — её кадр: вместо свечного рецепта она получает
-- тёплый, то есть фотографию как снята, без фильтра и без слоя. Это ровно то,
-- что владелец на ней и видел.
--
-- ОБРАТИМОСТЬ. Восстановить прежний выбор из этой строки нельзя: комнаты,
-- выбравшие свечной, и комнаты, выбравшие тёплый, после неё неотличимы.
-- Различие продукт больше нигде не использует (тон свечения `#E8A96B` удалён
-- вместе с веткой `bloomTint`), и терять его не жалко. Вернуть положение —
-- это новая миграция плюс рецепт, который видно на телефоне: дизайну сказано
-- письмом 63, что приёмка будет глазами, а не замером.
