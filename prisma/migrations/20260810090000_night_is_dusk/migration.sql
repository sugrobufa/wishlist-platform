-- Положение «ночь» упразднено (тикет 133, приёмка владельца 09.08.2026 и
-- согласие дизайна раундом 32).
--
-- ПОЧЕМУ. Владелец: «с ночным вариантом мы всё-таки сильно перебрали, почти
-- ничего не видно. Я думаю, вечерний и ночной вариант должен быть один и тот
-- же». Ночь переделывали дважды за сутки (тикеты 107 и 112), числа росли —
-- средняя светлота 0.238 → 0.268, — а глазами оставалось темно. Значит дело не
-- в множителе: между «вечером» и «ночью» разница есть в жизни, но не в
-- комнате, где смысл — рассмотреть вещи.
--
-- ДВА ОДИНАКОВЫХ ПОЛОЖЕНИЯ В НАСТРОЙКАХ — ЛОЖЬ ИНТЕРФЕЙСУ: человек выбрал бы
-- «ночь», увидел вечер и решил, что сломалось. Поэтому положение убрано
-- целиком, а не приравнено к вечернему. Дизайн согласился и довода за
-- отдельную ночь не имеет: «„праздник вечером" покрывается вечером, а будущему
-- экрану свет добавляется слоем, а не положением — вернуть положение всегда
-- дешевле, чем держать пустое».
--
-- РИСКА НЕТ. Поле строковое, значений было четыре; ни ключей, ни ограничений
-- на него не заведено, вычислять по нему нечего. Единственное, что меняется у
-- существующей комнаты, — её кадр: вместо ночного рецепта она получает
-- вечерний, тот самый, который владелец и просил.
--
-- ОБРАТИМОСТЬ. Восстановить прежний выбор из этой строки нельзя: комнаты,
-- выбравшие ночь, и комнаты, выбравшие вечер, после неё неотличимы. Различие
-- продукт больше нигде не использует (`TOD_FACTOR.night` тоже удалён), и
-- терять его не жалко. Вернуть положение — это новая миграция плюс рецепт,
-- ровно как пишет дизайн.
--
-- РОДНОЕ ВРЕМЯ СУТОК БАЗЫ ЭТО НЕ ТРОГАЕТ: четыре базы из десяти сняты ночью,
