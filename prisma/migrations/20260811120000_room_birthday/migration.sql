-- Безымянная «Дата» стала ДНЁМ РОЖДЕНИЯ (тикет 187, приёмка владельца
-- 11.08.2026, пункт 2).
--
-- ПОЧЕМУ. Третий шаг онбординга спрашивал «Дату» — слово, которое не называет
-- ничего: человек не знал ни чья это дата, ни повторяется ли она, ни что будет,
-- когда она пройдёт. И праздник в модели был один и навсегда: разовая отметка
-- протухала молча, комната тихо переставала напоминать, а спросить снова было
-- негде. День рождения — единственная дата, которую человек знает не думая, и
-- она повторяется сама.
--
-- ЧТО МЕНЯЕТСЯ В ДАННЫХ. Момент `occasionDate` (полночь UTC выбранного дня)
-- раскладывается на день, месяц и год. Ближайший праздник больше не хранится —
-- он считается на чтении от «сегодня» (src/server/birthday.ts).
--
-- НИ ОДНА ДАТА НЕ ТЕРЯЕТСЯ. Отметка писалась ровно полночью UTC (единственное
-- место записи — services/rooms), колонка `timestamp(3)` без зоны, поэтому
-- EXTRACT берёт тот самый день, который назвал человек: ни сдвига на сутки, ни
-- округления. Год переносится тоже — он больше ни на что не влияет и нигде не
-- показывается, но выбрасывать то, что человек ввёл, миграция не вправе.
-- Проверка — tests/birthday-migration.test.ts: он читает ЭТОТ файл и прогоняет
-- оператор ниже на данных стенда и на краях года.
--
-- ОБРАТИМОСТЬ. Обратная миграция собрала бы отметку из дня, месяца и года, но
-- у комнат, заведённых после этой строки, года нет — и взять его неоткуда,
-- кроме «ближайшего», а это уже другая дата. Возврат — отдельное решение.

ALTER TABLE "Room"
  ADD COLUMN "birthdayDay" INTEGER,
  ADD COLUMN "birthdayMonth" INTEGER,
  ADD COLUMN "birthdayYear" INTEGER;

-- Оператор между пометками читает и прогоняет tests/birthday-migration.test.ts.
-- migration:backfill
UPDATE "Room"
SET "birthdayDay" = EXTRACT(DAY FROM "occasionDate")::int,
    "birthdayMonth" = EXTRACT(MONTH FROM "occasionDate")::int,
    "birthdayYear" = EXTRACT(YEAR FROM "occasionDate")::int
WHERE "occasionDate" IS NOT NULL;
-- migration:backfill-end

ALTER TABLE "Room" DROP COLUMN "occasionDate";
