-- Отмена «хочу/люблю» (тикет 124, решение владельца 09.08.2026).
--
-- У вещи больше нет двух состояний. Различие переехало из ПОЛЯ в МЕСТО:
-- комната (`inHall = false`) — чего хочется, сокровищница (`inHall = true`) —
-- что уже моё. Колонка `Item.state` и тип `ItemState` уходят.
--
-- КУДА ПЕРЕЕХАЛИ ДАННЫЕ — правило одно и оно записано в тикете:
--   state = 'LOVE'  → на витрину: inHall := true («уже моё» и есть
--                     сокровищница). Уже лежащее на витрине не трогаем —
--                     условие `inHall = false` в UPDATE именно за этим;
--   state = 'WANT'  → остаётся в комнате: inHall не меняется (у «хочу» он
--                     всегда был false — витрина «хочу» не принимала).
-- Ничего не удаляется и не обнуляется: цена, размер, `desire`, даритель и год
-- остаются на своих колонках. Поэтому переезд ОБРАТИМ по данным настолько,
-- насколько это вообще возможно: «Вернуть в комнату» (inHall := false)
-- возвращает вещь в её `zone` со всеми полями, а восстановить прежнее
-- состояние из резервной копии можно правилом
--   state := CASE WHEN inHall THEN 'LOVE' ELSE 'WANT' END
-- ВЕРНО ДЛЯ ВСЕХ, КРОМЕ ОДНОГО СЛУЧАЯ, и его надо назвать честно: вещь
-- «люблю», лежавшая на витрине ДО этой миграции, неотличима от «люблю»,
-- которую сюда привёл этот UPDATE. Различие между ними продукт нигде не
-- использовал, и терять его не жалко; полное восстановление — только из
-- дампа.
--
-- Владельцу сказано прямо (тикет 124 §«Существующие данные»): в комнатах, где
-- «люблю» много, комната после миграции поредеет, а витрина разбухнет. Живых
-- комнат в Phase 1, кроме его собственной, нет — на стенде это лечится
-- пересевом.

-- 1. Переезд данных — ДО удаления колонки, иначе переезжать будет нечем.
UPDATE "Item" SET "inHall" = true WHERE "state" = 'LOVE' AND "inHall" = false;

-- 2. Индекс зоны больше не по состоянию, а по месту: и комната, и витрина
--    читаются выборкой «вещи комнаты в этой зоне с таким-то inHall».
DROP INDEX "Item_roomId_zone_state_idx";

-- 3. Сама колонка и тип.
ALTER TABLE "Item" DROP COLUMN "state";

DROP TYPE "ItemState";

CREATE INDEX "Item_roomId_zone_inHall_idx" ON "Item"("roomId", "zone", "inHall");
